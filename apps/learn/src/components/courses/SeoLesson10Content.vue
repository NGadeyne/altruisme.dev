      approche » ou « En savoir plus ».
    </p>
    <p>
      Ces formulations ne sont pas nécessairement incorrectes. Mais elles pourraient être utilisées
      sur le site de presque n'importe quelle entreprise. Elles n'expliquent pas clairement ce que
      tu proposes et ne permettent pas toujours à une personne qui découvre ton activité de
      comprendre immédiatement ce qu'elle va trouver.
    </p>
    <p>
      Prenons un exemple. Imaginons que tu sois photographe professionnel à Bordeaux et que tu
