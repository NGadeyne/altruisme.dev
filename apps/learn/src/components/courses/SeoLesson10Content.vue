      éventuelles. Si un changement d'adresse s'avère réellement nécessaire, il faudra le préparer
      correctement.
    </p>
    <h3>Le H1 : le titre principal visible sur la page</h3>
    <p>Le H1 est un titre HTML qui sert généralement à identifier le sujet principal d'une page.</p>
    <p>
      Contrairement au title, qui constitue notamment une information utilisée pour présenter la
      page dans les résultats Google, le H1 correspond à un titre présent dans le contenu lui-même.
    </p>
    <p>Il est donc normalement visible par les visiteurs lorsqu'ils consultent la page.</p>
    <p>
      Imaginons que notre photographe possède le title suivant : « Photographe de mariage à Bordeaux
      | Studio Horizon ».
    </p>
    <p>
      Sur sa page, il pourrait utiliser ce H1 : « Un reportage naturel pour raconter votre mariage à
      Bordeaux ».
    </p>
    <p>Les deux formulations sont différentes, mais elles présentent un sujet cohérent.</p>
    <p>
      Le title permet d'identifier directement la prestation et sa localisation. Le H1 développe
      davantage la promesse éditoriale proposée aux futurs mariés.
    </p>
    <p>Il n'est donc pas obligatoire que le title et le H1 soient identiques.</p>
    <p>
      En revanche, ils doivent rester suffisamment proches dans leur signification pour ne pas créer
      de confusion.
    </p>
    <p>
      Si le title annonce une prestation de photographie de mariage et que le H1 présente une
      formation destinée aux photographes professionnels, le visiteur risque de ne pas retrouver ce
      qu'il cherchait.
    </p>
    <p>Le H1 doit avant tout servir la compréhension du contenu.</p>
    <p>
      Il est généralement préférable d'utiliser un titre principal clairement identifiable,
      notamment pour faciliter la lecture et la structure sémantique de la page.
    </p>
    <p>Mais il ne faut pas non plus transformer cette recommandation en règle magique.</p>
    <p>
      La présence d'un seul H1 ne garantit pas une meilleure position sur Google, et l'utilisation
      de plusieurs éléments H1 n'entraîne pas automatiquement une pénalité.
    </p>
    <p>
      L'important est de conserver une hiérarchie logique et de rendre le sujet principal évident
      pour le lecteur.
    </p>
    <h3>Les H2 et H3 : organiser les informations</h3>
    <p>Une page ne se limite généralement pas à un titre et à quelques paragraphes.</p>
    <p>
      Lorsqu'un contenu devient plus développé, il est utile de l'organiser autour de différentes
      sections.
    </p>
    <p>C'est notamment le rôle des titres H2 et H3.</p>
    <p>
      Les H2 permettent de présenter les grandes parties du contenu. Les H3 servent à organiser des
      sous-parties à l'intérieur de ces sections.
    </p>
    <p>Imaginons que notre photographe possède une page consacrée à ses prestations de mariage.</p>
    <p>
      Il pourrait commencer par un H1 présentant son service, puis organiser son contenu autour de
      plusieurs H2 : son approche photographique, les prestations proposées, ses réalisations et les
      modalités de contact.
    </p>
    <p>
      Si la section consacrée aux prestations contient plusieurs formules distinctes, il pourrait
      utiliser des H3 pour présenter chacune d'elles.
    </p>
    <p>
      Cette hiérarchie facilite la lecture, notamment pour les internautes qui parcourent rapidement
      une page afin de retrouver les informations qui les intéressent.
    </p>
    <p>
      Elle contribue également à une structure de contenu plus compréhensible pour les technologies
      d'assistance et les moteurs de recherche.
    </p>
    <p>Mais là encore, il faut éviter une approche purement mécanique.</p>
    <p>
      Ajouter un H2 contenant un mot-clé ne garantit pas une amélioration des positions. De même,
      répéter la même expression dans tous les sous-titres n'apporte pas nécessairement davantage de
      pertinence.
    </p>
    <p>Les titres doivent décrire les informations qu'ils introduisent.</p>
    <p>
      Une section consacrée aux prestations gagnera à posséder un intitulé comme « Nos prestations
      de photographie de mariage » plutôt qu'un titre générique comme « Nos solutions ».
    </p>
    <p>
      À l'inverse, il n'est pas nécessaire d'allonger artificiellement tous les titres pour y
      ajouter une localisation ou plusieurs variations de mots-clés.
    </p>
    <p>
      <strong
        >Une bonne structure de titres doit permettre de comprendre le contenu d'une page sans avoir
        besoin de lire immédiatement chaque paragraphe.</strong
      >
    </p>
    <p>C'est un excellent principe à garder en tête lorsque tu commences à optimiser tes pages.</p>
    <h2>Construire une page cohérente plutôt que multiplier les mots-clés</h2>
    <p>
      Maintenant que tu connais le rôle de ces différents éléments, il est important de comprendre
      comment ils fonctionnent ensemble.
    </p>
    <p>
      Dans le module 3, nous avons appris à associer les mots-clés aux pages qui correspondent aux
      besoins des internautes.
    </p>
    <p>
      Imaginons que tu aies identifié « photographe mariage Bordeaux » comme expression principale
      pour une page consacrée à cette prestation.
    </p>
    <p>
      Cela ne signifie pas que tu dois répéter exactement cette expression dans le title, la meta
      description, le H1, tous les H2 et chaque paragraphe.
    </p>
    <p>Ton objectif est plutôt de construire un ensemble cohérent.</p>
    <p>
      Le title doit présenter clairement le sujet. La meta description doit résumer utilement le
      contenu. Le H1 doit permettre de comprendre ce que propose la page. Les sous-titres doivent
      organiser les différentes informations attendues par les visiteurs.
    </p>
    <p>
      Lorsque ces éléments sont cohérents avec la recherche ciblée, tu n'as pas besoin de multiplier
      les répétitions artificielles.
    </p>
    <p>
      Par exemple, notre photographe pourrait utiliser l'expression « photographe de mariage à
      Bordeaux » dans son title, parler de « reportage naturel » dans son H1 et organiser ses
      sections autour de ses prestations, de ses réalisations et de son accompagnement.
    </p>
    <p>Le vocabulaire varie naturellement, mais le sujet reste identifiable.</p>
    <p>
      Cette cohérence est plus utile qu'une accumulation d'expressions conçues uniquement pour
      attirer l'attention d'un algorithme.
    </p>
    <p>
      Il faut également se souvenir d'une notion importante :
      <strong
        >l'optimisation des balises ne peut pas compenser un contenu qui ne répond pas aux attentes
        des internautes</strong
      >.
    </p>
    <p>
      Si la page présente uniquement trois phrases vagues, modifier ses titres ne suffira pas
      nécessairement à la rendre pertinente pour une recherche concurrentielle.
    </p>
    <p>
      Les éléments que nous étudions aujourd'hui permettent de mieux présenter et structurer les
      contenus.
    </p>
