    <p><code>https://exemple.fr/prestations-mariage</code></p>
    <p>
      Cette adresse est parfaitement compréhensible. La modifier uniquement pour ajouter le mot «
      Bordeaux » n'est pas nécessairement utile.
    </p>
    <p>
      Et si tu décidais malgré tout de la remplacer, les personnes qui utilisent l'ancienne adresse
      pourraient rencontrer une erreur si aucune redirection n'est prévue.
    </p>
    <p>
      Il faudrait alors mettre en place une redirection permanente appropriée, généralement de type
      301 ou 308, et mettre à jour les liens internes qui pointent vers l'ancienne URL.
    </p>
    <p>
      Il pourrait également être nécessaire de vérifier le sitemap et les informations canoniques
      associées à la nouvelle adresse.
    </p>
    <p>
      Une modification d'URL peut donc constituer une petite migration, avec des conséquences sur
      l'exploration et l'indexation.
    </p>
    <p>
      Pour cette raison,
      <strong
        >nous ne modifierons pas les URL existantes simplement pour les rendre plus jolies ou y
