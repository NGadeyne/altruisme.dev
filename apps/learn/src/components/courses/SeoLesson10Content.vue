    </p>
    <p>
      L'objectif n'est pas de répéter un mot-clé partout où cela est possible. Il est de construire
      un ensemble cohérent, depuis la présentation de la page dans Google jusqu'à son contenu.
    </p>
    <h2>Comprendre les principaux éléments d'une page web</h2>
    <p>
      Lorsqu'une personne découvre ton site depuis Google, elle ne commence pas directement par lire
      tous tes paragraphes. Elle voit généralement un résultat constitué de plusieurs éléments,
      notamment un titre cliquable, des informations sur le site et un extrait de texte.
    </p>
    <p>
      Si ce résultat correspond à ce qu'elle recherche, elle peut décider de cliquer pour consulter
      la page. Elle découvre alors un titre principal, différents sous-titres et les informations
      que tu as rédigées.
    </p>
    <p>
      Ces éléments participent à la compréhension de ton contenu, mais ils ne possèdent pas tous le
      même rôle.
    </p>
    <p>
      Nous allons donc distinguer cinq notions : le title, la meta description, l'URL, le H1 et les
      sous-titres H2 et H3.
    </p>
    <p>
      Tu n'as pas besoin de savoir programmer pour les comprendre ni pour modifier la plupart
      d'entre eux. De nombreux outils de création de sites proposent des champs spécifiques pour les
      renseigner.
    </p>
    <h3>Le title : présenter clairement le sujet dans Google</h3>
    <p>
      Le <em>title</em> est un élément HTML qui permet de définir le titre d'une page web. Il est
      notamment utilisé parmi les différentes sources que Google peut exploiter pour générer le
      titre cliquable affiché dans ses résultats de recherche.
    </p>
    <p>Il apparaît également généralement dans l'onglet du navigateur.</p>
    <p>
      Imaginons que notre photographe possède une page consacrée à ses prestations de mariage. Son
      title actuel est « Prestations | Studio Horizon ».
    </p>
    <p>
      Ce titre nous indique que la page présente des services proposés par une entreprise, mais il
      ne permet pas de comprendre précisément lesquels. Une personne qui recherche un photographe de
      mariage à Bordeaux ne sait pas immédiatement si le résultat correspond à son besoin.
    </p>
    <p>
      Nous pourrions donc proposer une formulation plus descriptive : « Photographe de mariage à
      Bordeaux | Studio Horizon ».
    </p>
    <p>
      Cette nouvelle version présente le service principal, précise sa localisation et conserve le
      nom de l'entreprise. Elle permet de mieux comprendre le contenu auquel le visiteur peut
      s'attendre.
    </p>
    <p>
      Mais attention à une nuance importante :
      <strong>Google ne garantit pas qu'il affichera exactement le title que tu as renseigné</strong
      >.
    </p>
    <p>
      Pour générer le titre cliquable d'un résultat, Google peut utiliser plusieurs informations,
      notamment l'élément title, le titre principal visible sur la page et d'autres textes. Il peut
      donc choisir une formulation différente de celle que tu as définie.
    </p>
    <p>
      Ton objectif n'est pas de contrôler parfaitement l'affichage du résultat. Il est de fournir à
      Google et aux internautes un titre clair, descriptif et fidèle au contenu.
    </p>
    <h4>Faut-il respecter une longueur précise ?</h4>
    <p>
      Tu trouveras régulièrement des recommandations conseillant de limiter les titles à 50 ou 60
      caractères.
    </p>
    <p>
      Ces indications peuvent constituer des repères pratiques pour éviter des titres inutilement
      longs, mais elles ne correspondent pas à une limite absolue imposée par Google.
    </p>
    <p>
      L'affichage dépend notamment de la largeur disponible, de l'appareil utilisé et des caractères
      qui composent le titre.
    </p>
    <p>
      Google peut raccourcir un titre lorsque l'espace ne permet pas de l'afficher intégralement.
    </p>
    <p>
      Plutôt que de compter systématiquement chaque caractère, concentre-toi donc sur la clarté de
      l'information. Place les éléments importants relativement tôt dans le title lorsqu'ils
      permettent de comprendre rapidement le sujet.
    </p>
    <p>
      Évite également les titres trop génériques, les formulations artificiellement longues et les
      répétitions de mots-clés.
    </p>
    <p>
      Par exemple, un title comme « Photographe mariage Bordeaux | Photographie mariage Bordeaux |
      Reportage mariage Bordeaux » ne présente aucun intérêt particulier pour le lecteur.
    </p>
    <p>
      Il donne surtout l'impression d'avoir été construit pour répéter plusieurs fois la même
      expression.
    </p>
    <p>Un titre simple, précis et naturel reste généralement un meilleur point de départ.</p>
    <h3>La meta description : présenter le contenu et susciter l'intérêt</h3>
    <p>
      La <em>meta description</em> est un autre élément HTML. Elle permet de proposer un court
      résumé du contenu de ta page.
    </p>
    <p>
      Google peut utiliser cette description pour construire l'extrait qui apparaît sous un résultat
      de recherche.
    </p>
    <p>Reprenons notre photographe.</p>
    <p>
      Imaginons que sa page possède cette description : « Bienvenue sur notre site. Découvrez notre
      entreprise et nos différentes prestations. »
    </p>
    <p>
      Cette formulation ne fournit presque aucune information spécifique. Elle pourrait convenir à
      un grand nombre de pages et ne permet pas de comprendre ce que propose réellement le
      photographe.
    </p>
    <p>
      Une version plus pertinente pourrait être : « Photographe de mariage à Bordeaux, je réalise
      des reportages naturels pour raconter votre journée. Découvrez mes prestations et mes
      réalisations. »
    </p>
    <p>
      Cette description présente le service proposé, apporte une information sur l'approche du
      professionnel et invite le lecteur à découvrir son travail.
    </p>
    <p>
      Elle ne garantit pas davantage de clics, mais elle constitue une présentation plus utile pour
      une personne qui recherche ce type de prestation.
    </p>
    <p>
      Il faut toutefois comprendre que Google n'utilise pas systématiquement la meta description
      renseignée.
    </p>
    <p>
      Le moteur de recherche peut sélectionner un autre passage de la page lorsqu'il considère que
      celui-ci correspond davantage à la recherche de l'internaute.
    </p>
    <p>Une même page peut donc être présentée avec des extraits différents selon les requêtes.</p>
    <p>
      De plus, la meta description n'est pas utilisée comme un facteur direct permettant d'améliorer
      le classement d'une page simplement parce qu'elle contient certains mots-clés.
    </p>
    <p>
      Son rôle principal est de contribuer à la présentation du contenu lorsqu'elle est retenue pour
      l'extrait.
    </p>
    <p>
      Comme pour le title, il n'existe pas de nombre universel de caractères garantissant un
      affichage intégral. Google peut raccourcir l'extrait selon l'espace disponible.
    </p>
    <p>
      Privilégie donc une description claire, fidèle au contenu et suffisamment concise pour être
      comprise rapidement.
    </p>
    <p>
      Enfin, essaie d'éviter les descriptions génériques répétées sur toutes les pages de ton site.
      Une page consacrée à la photographie de mariage ne devrait pas nécessairement posséder la même
      meta description qu'une page dédiée aux portraits professionnels.
    </p>
    <p>
      Chaque page présente un sujet différent et mérite, lorsque cela est pertinent, une description
      adaptée.
    </p>
    <h3>L'URL : une adresse simple et compréhensible</h3>
    <p>L'URL correspond à l'adresse permettant d'accéder à une page.</p>
    <p>
      Par exemple, notre photographe pourrait posséder une page accessible depuis l'adresse suivante
      :
    </p>
    <p><code>https://exemple.fr/photographe-mariage-bordeaux</code></p>
    <p>Cette adresse permet de comprendre assez facilement le sujet du contenu.</p>
    <p>
      À l'inverse, une URL comme <code>https://exemple.fr/page?id=4827</code> ne donne que très peu
      d'informations à une personne qui la consulte.
    </p>
    <p>
      Google recommande généralement d'utiliser des URL descriptives et une organisation logique
      lorsque cela est possible.
    </p>
    <p>
      Les mots peuvent notamment être séparés par des traits d'union, ce qui facilite leur lecture.
    </p>
    <p>
      Mais attention à une idée reçue :
      <strong
        >une URL contenant exactement ton mot-clé principal ne garantit pas un meilleur
        classement</strong
      >.
    </p>
    <p>
      Google est capable de comprendre les contenus d'un site même lorsque leurs adresses ne sont
      pas parfaitement optimisées.
    </p>
    <p>
      Il serait donc excessif de considérer qu'une page possède un mauvais référencement simplement
      parce que son URL n'est pas idéale.
    </p>
    <p>
      L'objectif est avant tout de proposer des adresses compréhensibles, cohérentes avec
      l'organisation du site et faciles à utiliser.
    </p>
    <h4>Faut-il modifier les URL existantes ?</h4>
    <p>C'est ici qu'une précaution particulièrement importante s'impose.</p>
    <p>
      Si tu crées une nouvelle page, il est généralement intéressant de choisir dès le départ une
      URL descriptive.
    </p>
    <p>
      Mais si ta page existe depuis plusieurs mois ou plusieurs années, modifier son adresse peut
      entraîner des conséquences qu'il faut anticiper.
    </p>
