    <h3>Étape 1 — Reprendre l'intention de recherche</h3>
    <p>
      Avant de modifier quoi que ce soit, commençons par une question simple : que souhaite
      accomplir une personne qui recherche « photographe mariage Bordeaux » ?
    </p>
    <p>
      Elle souhaite probablement découvrir un professionnel capable de réaliser un reportage de
      mariage dans cette zone géographique.
    </p>
    <p>
      Elle peut chercher à consulter des réalisations, comprendre les prestations proposées,
      découvrir un style photographique ou prendre contact.
    </p>
    <p>Notre page doit donc présenter clairement cette offre.</p>
    <p>
      C'est cette intention qui va guider nos modifications, et non la volonté de placer
      mécaniquement un mot-clé dans chaque élément.
    </p>
    <h3>Étape 2 — Examiner les éléments actuels</h3>
    <p>Imaginons que notre photographe possède actuellement les éléments suivants.</p>
    <p><strong>Title actuel :</strong> « Prestations | Studio Horizon »</p>
    <p>
      <strong>Meta description actuelle :</strong> « Découvrez nos différentes prestations et notre
      accompagnement personnalisé. »
    </p>
    <p><strong>URL actuelle :</strong> <code>https://exemple.fr/prestations</code></p>
    <p><strong>H1 actuel :</strong> « Mes services »</p>
    <p>
      <strong>Sous-titres actuels :</strong> « Mon approche », « Mes réalisations » et « Contact ».
    </p>
    <p>Ces éléments ne sont pas tous inutiles.</p>
    <p>Mais ils présentent un problème commun : ils restent relativement génériques.</p>
    <p>
      Le title ne permet pas d'identifier le type de prestation. La meta description ne précise pas
      le sujet de la page. Le H1 ne donne pas davantage d'informations sur le service concerné.
    </p>
    <p>
      Quant aux sous-titres, ils permettent de distinguer certaines sections, mais pourraient être
      plus explicites.
    </p>
    <p>Nous allons donc essayer d'améliorer la clarté de cet ensemble.</p>
    <h3>Étape 3 — Réécrire le title</h3>
    <p>Commençons par le title.</p>
    <p>
      Nous souhaitons permettre à une personne qui découvre le résultat dans Google de comprendre
      rapidement qu'il s'agit d'une prestation de photographie de mariage à Bordeaux.
    </p>
    <p>Nous remplaçons donc « Prestations | Studio Horizon » par :</p>
    <p><strong>« Photographe de mariage à Bordeaux | Studio Horizon »</strong></p>
    <p>
      Ce nouveau titre présente directement le service, la localisation et le nom de l'entreprise.
    </p>
    <p>Il reste relativement concis et fidèle au contenu de la page.</p>
    <p>
      Nous ne cherchons pas à ajouter toutes les variations de mots-clés identifiées dans notre
      tableau.
    </p>
    <p>Une seule formulation claire suffit pour présenter le sujet principal.</p>
    <h3>Étape 4 — Améliorer la meta description</h3>
    <p>Passons maintenant à la description.</p>
    <p>
      Notre version actuelle, « Découvrez nos différentes prestations et notre accompagnement
      personnalisé », ne fournit presque aucune information spécifique.
    </p>
    <p>Nous pourrions la remplacer par :</p>
    <p>
      <strong
        >« Photographe de mariage à Bordeaux, je réalise des reportages naturels pour raconter votre
        journée. Découvrez mon approche, mes prestations et mes réalisations. »</strong
      >
    </p>
    <p>Cette formulation permet de comprendre le service et l'approche du photographe.</p>
    <p>Elle donne également une idée des informations disponibles sur la page.</p>
    <p>
      Bien entendu, cette description doit correspondre à la réalité. Il ne faudrait pas promettre
      des réalisations, des tarifs ou une prestation particulière si ces informations ne sont pas
      présentes sur le site.
    </p>
    <p>
      Notre objectif est de présenter fidèlement le contenu, pas d'attirer des clics avec une
      promesse trompeuse.
    </p>
    <h3>Étape 5 — Améliorer le H1 et les sous-titres</h3>
    <p>Nous allons maintenant examiner le contenu visible.</p>
    <p>
      Le H1 actuel est « Mes services ». Il est compréhensible, mais ne permet pas d'identifier
      précisément la prestation.
    </p>
    <p>Nous pourrions le remplacer par :</p>
    <p><strong>H1 — Un reportage naturel pour raconter votre mariage à Bordeaux</strong></p>
    <p>
      Cette formulation reste cohérente avec le title, tout en proposant une approche davantage
      orientée vers les futurs mariés.
    </p>
    <p>
      Nous pouvons ensuite améliorer les sous-titres pour qu'ils correspondent aux différentes
      informations proposées.
    </p>
    <p>
      La section « Mon approche » pourrait devenir « Une approche naturelle de la photographie de
      mariage ».
    </p>
    <p>La section « Mes réalisations » pourrait devenir « Découvrez mes reportages de mariage ».</p>
    <p>
      Enfin, une section consacrée au déroulement de la prestation pourrait être intitulée « Comment
      se déroule votre reportage ? ».
    </p>
    <p>Le but n'est pas de créer de nouvelles sections simplement pour ajouter des titres.</p>
    <p>
      Nous cherchons à utiliser des intitulés qui décrivent correctement les contenus existants.
    </p>
    <p>
      Si certaines informations importantes sont absentes, nous pourrons le noter pour la prochaine
      leçon, consacrée à l'amélioration des contenus.
    </p>
    <h3>Étape 6 — Examiner l'URL sans la modifier inutilement</h3>
    <p>Il nous reste à examiner l'adresse de la page.</p>
    <p>Dans notre exemple, l'URL actuelle est :</p>
    <p><code>https://exemple.fr/prestations</code></p>
    <p>Cette adresse reste relativement générale, mais elle fonctionne déjà.</p>
    <p>Nous pourrions imaginer une adresse plus descriptive pour une nouvelle page, comme :</p>
    <p><code>https://exemple.fr/photographe-mariage-bordeaux</code></p>
    <p>
      Mais si la page actuelle est déjà publiée, possède des liens ou reçoit des visites, il serait
      imprudent de modifier son adresse sans examiner les conséquences.
    </p>
    <p>Pour cette première optimisation, nous décidons donc de conserver l'URL existante.</p>
    <p>
      Nous notons simplement qu'une évolution pourrait être étudiée plus tard, si elle présente un
      véritable intérêt et si les redirections nécessaires peuvent être correctement mises en place.
    </p>
    <p>
      C'est une décision importante : toutes les améliorations théoriquement possibles ne doivent
      pas nécessairement être réalisées.
    </p>
    <h3>Étape 7 — Appliquer et vérifier les modifications</h3>
    <p>
      Nous disposons maintenant d'une proposition pour le title, la meta description, le H1 et les
      principaux sous-titres.
    </p>
    <p>
      Si notre photographe utilise un CMS comme WordPress, il peut généralement modifier le H1 et
      les sous-titres depuis l'éditeur de page, en utilisant les niveaux de titres appropriés.
    </p>
    <p>
      Le title et la meta description sont souvent accessibles depuis les paramètres SEO de la page
      ou une extension adaptée.
    </p>
    <p>
      Sur d'autres plateformes de création de sites, les emplacements peuvent être différents, mais
      la logique reste similaire.
    </p>
    <p>
      Avant de publier, nous relisons l'ensemble pour vérifier que les informations sont exactes,
      que les titres correspondent bien au contenu et qu'aucune répétition artificielle n'a été
      introduite.
    </p>
    <p>
      Une fois les modifications enregistrées, nous ouvrons la page publiée pour vérifier son
      affichage.
    </p>
    <p>
      Nous pouvons également consulter les informations SEO renseignées dans l'éditeur ou dans le
      code source de la page pour confirmer que les modifications ont bien été prises en compte.
    </p>
    <p>
      Si la page est déjà indexée, Google devra éventuellement la réexplorer et traiter à nouveau
      son contenu avant que les changements puissent être visibles dans les résultats de recherche.
    </p>
    <p>
      Cela peut prendre du temps, et il n'est pas garanti que Google affiche exactement les
      nouvelles formulations.
    </p>
    <h3>Ce que cette démonstration nous apprend</h3>
    <p>
      Nous venons d'améliorer plusieurs éléments importants d'une page en utilisant un groupe de
      mots-clés et une intention de recherche identifiés dans le module précédent.
    </p>
    <p>
      Nous avons rendu le title plus descriptif, rédigé une meta description plus utile et clarifié
      la structure des titres visibles.
    </p>
    <p>
      Nous avons également pris une décision importante concernant l'URL : ne pas la modifier
      inutilement.
    </p>
    <p>
      Ces optimisations ne garantissent pas une progression sur Google. En revanche, elles
      permettent de présenter plus clairement la page, de rendre son sujet plus évident et de
      construire une meilleure cohérence entre les recherches ciblées et le contenu proposé.
    </p>
    <p>
      <strong
        >Une bonne optimisation ne consiste pas à remplir des champs avec des mots-clés. Elle
        consiste à rendre une page plus claire, plus cohérente et plus utile pour les personnes qui
        la découvrent.</strong
      >
    </p>
    <p>C'est cette méthode que nous allons maintenant appliquer à ton site.</p>
    <h2>À toi de jouer — Optimise les titres d'une page stratégique</h2>
    <p>
      Maintenant que tu comprends le rôle des principaux éléments d'une page, il est temps de
      réaliser ta première optimisation concrète.
    </p>
    <p>
      Dans le module 3, tu as identifié trois groupes de mots-clés prioritaires et commencé à les
      associer aux pages correspondantes.
    </p>
    <p>
      Pour cet exercice, nous allons sélectionner l'une de ces pages et améliorer ses principaux
      éléments.
    </p>
    <p>
      L'objectif n'est pas de réécrire tout ton contenu ni de modifier sa structure technique en
      profondeur. Nous allons simplement travailler les éléments qui permettent de présenter
      clairement son sujet.
    </p>
    <p><strong>Durée estimée : 15 à 20 minutes.</strong></p>
    <h3>Étape 1 — Choisis une page et son mot-clé principal</h3>
    <p>
      Commence par reprendre ton tableau de recherche de mots-clés et sélectionne l'une des trois
      priorités définies à la fin du module précédent.
    </p>
    <p>Identifie ensuite la page de ton site qui correspond à cette recherche.</p>
    <p>
      Il peut s'agir de ta page d'accueil, d'une page présentant une prestation ou d'un contenu
      important pour attirer de futurs visiteurs.
    </p>
    <p>
      Avant de continuer, vérifie que tu comprends bien l'intention principale associée au mot-clé.
    </p>
    <p>L'objectif est de savoir précisément quel besoin ta page doit satisfaire.</p>
    <h3>Étape 2 — Examine les éléments existants</h3>
    <p>Ouvre maintenant cette page dans ton navigateur et dans ton outil de création de site.</p>
    <p>Retrouve son title, sa meta description, son H1 et ses principaux sous-titres.</p>
    <p>Prends quelques instants pour examiner leur clarté.</p>
    <p>
      Le title permet-il de comprendre immédiatement le sujet ? La meta description présente-t-elle
      fidèlement le contenu ? Le H1 est-il cohérent avec la recherche ciblée ? Les sous-titres
      permettent-ils de retrouver facilement les informations principales ?
    </p>
    <p>Note les éléments qui te semblent trop vagues, répétitifs ou insuffisamment précis.</p>
    <h3>Étape 3 — Prépare une version améliorée</h3>
    <p>
      À partir de ton mot-clé principal et de l'intention de recherche, propose un nouveau title et
      une meta description plus descriptive.
    </p>
    <p>Vérifie ensuite si ton H1 doit être clarifié.</p>
    <p>
      Examine également les principaux sous-titres pour déterminer s'ils présentent correctement les
      différentes sections de ta page.
    </p>
    <p>Tu n'as pas besoin d'intégrer exactement la même expression dans chaque élément.</p>
    <p>
      Privilégie des formulations naturelles et cohérentes avec les informations réellement
      présentes.
    </p>
    <h3>Étape 4 — Applique les modifications nécessaires</h3>
    <p>
      Si tu disposes des accès nécessaires, modifie les éléments concernés dans ton outil de
      création de site.
    </p>
    <p>
      Prends le temps de vérifier que la mise en page reste correcte et que les titres ne créent pas
      de confusion.
    </p>
    <p>
      Si tu ne sais pas où modifier le title ou la meta description, recherche les paramètres SEO de
      ta page dans ton CMS.
    </p>
    <p>
      <strong>Ne modifie pas l'URL d'une page existante pour cet exercice.</strong> Si son adresse
      te semble peu claire, conserve simplement cette observation pour une éventuelle optimisation
      future.
    </p>
    <h3>Étape 5 — Vérifie le résultat</h3>
    <p>
      Une fois les modifications publiées, ouvre ta page et vérifie que son titre principal et ses
      sous-titres apparaissent correctement.
    </p>
    <p>Contrôle également les informations SEO renseignées dans ton éditeur.</p>
    <p>
      Conserve éventuellement une version avant/après de tes modifications afin de garder une trace
      de ton travail.
    </p>
    <p>
      Tu pourras ensuite observer l'évolution de la page dans Google Search Console, en gardant à
      l'esprit que les performances peuvent dépendre de nombreux facteurs et qu'une modification de
      title ne garantit pas davantage de clics.
    </p>
    <p>
      <strong>Ton résultat attendu :</strong> avoir amélioré le title, la meta description et, si
      nécessaire, les titres visibles d'une page stratégique, tout en conservant une cohérence avec
      son intention de recherche principale.
    </p>
    <p>
      Dans « Mon plan d'action », tu peux maintenant marquer l'action « Optimiser les titres et
      balises d'une page » comme terminée.
    </p>
