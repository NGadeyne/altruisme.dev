      alternatives ou des ressources qui n'ont pas vocation à apparaître dans Google.
    </p>
    <p>Ces situations ne représentent pas nécessairement des erreurs.</p>
    <p>Imaginons que notre photographe possède dix pages importantes pour son activité.</p>
    <p>
