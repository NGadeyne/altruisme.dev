    <h2>Comprendre ce que Google Analytics apporte de plus</h2>
    <p>
      Google Search Console permet principalement de comprendre ce qui se passe dans les résultats
      de recherche Google, avant l'arrivée sur ton site.
    </p>
    <p>Mais que se passe-t-il après le clic ?</p>
    <p>C'est ici qu'un outil de mesure d'audience, comme Google Analytics, peut devenir utile.</p>
    <p>
      Google Analytics 4, généralement appelé GA4, permet notamment d'analyser les sessions, les
      pages consultées, les sources de trafic et certaines actions réalisées sur le site.
    </p>
    <p>Contrairement à Search Console, il ne se limite pas à la visibilité dans Google Search.</p>
    <p>
      Il peut également fournir des informations sur les visites provenant d'autres sources, comme
      les réseaux sociaux, les sites référents ou certaines campagnes marketing.
    </p>
    <p>Mais nous allons surtout nous intéresser au trafic issu de la recherche naturelle.</p>
    <h3>Comprendre les sessions issues de la recherche organique</h3>
    <p>
      Dans GA4, une session correspond à une période d'interaction d'un utilisateur avec ton site ou
      ton application.
    </p>
    <p>
      Pour examiner le trafic SEO, tu peux consulter les rapports d'acquisition et sélectionner les
      sessions attribuées à la recherche organique, souvent appelée <em>Organic Search</em>.
    </p>
    <p>
      Imaginons que notre photographe enregistre 300 sessions issues de la recherche organique
      pendant un mois.
    </p>
    <p>
      Ces sessions correspondent à des visites attribuées à ce canal selon les règles de mesure de
      l'outil.
    </p>
    <p>Mais elles ne doivent pas être confondues avec les clics affichés dans Search Console.</p>
    <p>
      Une même personne peut générer plusieurs interactions, et les deux outils ne comptabilisent
      pas exactement les mêmes événements.
    </p>
    <p>
      Le trafic organique dans Analytics peut également inclure plusieurs moteurs de recherche,
      tandis qu'un rapport Search Console consacré à la recherche Google mesure uniquement les
      résultats du service concerné.
    </p>
    <h3>Pourquoi les clics Search Console et les sessions Analytics sont-ils différents ?</h3>
    <p>
      Imaginons que Search Console indique 250 clics sur une période, tandis que GA4 présente 220
      sessions organiques attribuées à Google.
    </p>
    <p>Tu pourrais penser qu'un outil fonctionne mal.</p>
    <p>Mais ces écarts peuvent être normaux.</p>
    <p>
      Les clics et les sessions sont calculés différemment. La collecte Analytics dépend également
      de la configuration du site, des choix de consentement, des dispositifs de mesure et des
      règles d'attribution.
    </p>
    <p>
      Certaines visites peuvent ne pas être enregistrées par Analytics, tandis que plusieurs clics
      peuvent correspondre à une même session.
    </p>
    <p>
      Il faut également tenir compte des différences de périmètre, de dates et de fuseaux horaires.
    </p>
    <p>
      Google recommande donc de comparer principalement les tendances plutôt que de chercher à
      obtenir des chiffres strictement identiques.
    </p>
    <p>
      Si les deux outils montrent une progression cohérente du trafic, cette évolution peut être
      intéressante.
    </p>
    <p>
      Si les écarts deviennent particulièrement importants, il faudra examiner la configuration et
      les périmètres de mesure.
    </p>
    <p>
      <strong
        >Search Console et Analytics ne sont pas deux instruments censés afficher le même nombre.
        Ils apportent des informations complémentaires sur la découverte du site et son
        utilisation.</strong
      >
    </p>
    <h2>Mesurer les actions importantes pour ton activité</h2>
    <p>Jusqu'à présent, nous avons étudié la visibilité et les visites.</p>
    <p>
      Mais pour de nombreux entrepreneurs, l'indicateur le plus intéressant concerne les actions
      réalisées par les visiteurs.
    </p>
    <p>Imaginons que notre photographe reçoit davantage de trafic depuis Google.</p>
    <p>C'est encourageant.</p>
    <p>
      Mais ce qui l'intéresse particulièrement, c'est de savoir si certaines personnes demandent un
      devis ou prennent contact pour réserver une prestation.
    </p>
    <p>
      Dans GA4, les interactions importantes peuvent être mesurées à l'aide d'événements, dont
      certains peuvent être désignés comme <em>événements clés</em>.
    </p>
    <p>
      Ces événements permettent de suivre des actions particulièrement pertinentes pour ton
      activité.
    </p>
    <p>Mais ils doivent être correctement configurés.</p>
    <h3>Choisir des actions qui correspondent à un véritable résultat</h3>
    <p>
      Pour notre photographe, l'envoi réussi d'un formulaire de demande de devis peut constituer un
      événement clé.
    </p>
    <p>Pour une boutique en ligne, un achat représente une action commerciale importante.</p>
    <p>
      Pour une plateforme de formation, une inscription ou une commande peut également être
      pertinente.
    </p>
    <p>Il faut cependant distinguer une action intermédiaire d'un résultat réel.</p>
    <p>Imaginons que notre photographe possède un bouton « Demander un devis ».</p>
    <p>Un clic sur ce bouton ne signifie pas nécessairement qu'un formulaire a été envoyé.</p>
    <p>
      De même, une visite sur la page de contact ne correspond pas automatiquement à une demande
      commerciale.
    </p>
    <p>
      Si tu souhaites mesurer les demandes de devis, il est préférable, lorsque cela est
      techniquement possible, de suivre la validation effective du formulaire plutôt que le simple
      clic sur le bouton.
    </p>
    <p>
      L'objectif est de choisir des indicateurs qui se rapprochent réellement de ce que tu souhaites
      obtenir.
    </p>
    <h3>Mesurer la qualité des demandes, pas seulement leur nombre</h3>
    <p>
      Imaginons que notre photographe reçoive dix demandes de renseignements provenant de son site.
    </p>
    <p>Il pourrait considérer qu'il a obtenu dix opportunités commerciales.</p>
    <p>
      Mais certaines demandes peuvent concerner des prestations qu'il ne propose pas, des dates
      auxquelles il n'est pas disponible ou des budgets incompatibles avec son offre.
    </p>
    <p>
      Il peut donc être utile de distinguer les demandes reçues des demandes réellement qualifiées.
    </p>
    <p>
      Ce suivi peut être réalisé simplement dans un tableau commercial, même si toutes les
      informations ne sont pas directement disponibles dans Analytics.
    </p>
    <p>
      Pour un indépendant, quelques indicateurs peuvent suffire : nombre de demandes reçues,
      demandes correspondant aux prestations proposées et éventuellement clients effectivement
      signés.
    </p>
    <p>
      Il n'est pas nécessaire de construire une infrastructure d'analyse complexe dès le départ.
    </p>
    <p>
      Mais il faut éviter de considérer que toutes les visites et toutes les conversions possèdent
      nécessairement la même valeur.
    </p>
    <p>
      <strong
        >Le référencement doit contribuer à tes objectifs réels. Cent visiteurs intéressés par une
        prestation peuvent parfois être plus utiles que mille visiteurs qui ne correspondent pas à
        ton public.</strong
      >
    </p>
    <h2>Les indicateurs qui peuvent te distraire de l'essentiel</h2>
    <p>
      Lorsque tu commences à utiliser plusieurs outils SEO, tu découvres rapidement de nombreux
      scores.
    </p>
    <p>
      Certains représentent la popularité d'un domaine, d'autres estiment un trafic potentiel ou
      calculent un niveau de difficulté sur des mots-clés.
    </p>
    <p>Ces indicateurs peuvent parfois apporter des informations utiles.</p>
    <p>Mais ils ne doivent pas tous devenir des objectifs à suivre chaque mois.</p>
    <p>
      Dans le module 7, nous avons notamment étudié le Domain Rating, le Domain Authority et le
      Trust Flow.
    </p>
    <p>Ces métriques sont proposées par des entreprises privées.</p>
    <p>Elles ne constituent pas des notes officielles attribuées par Google.</p>
    <p>
      Un DR qui augmente ne garantit donc pas une progression des clics ni des demandes
      commerciales.
    </p>
    <p>
      De même, certains outils présentent des estimations de trafic SEO calculées à partir de
      mots-clés et de positions observées.
    </p>
    <p>Ces estimations peuvent servir à comparer des sites ou à explorer un marché.</p>
    <p>Mais elles ne correspondent pas nécessairement aux visites réellement enregistrées.</p>
    <p>
      Il est donc préférable d'utiliser tes propres données Search Console et Analytics lorsqu'elles
      sont disponibles.
    </p>
    <h3>Le piège du trafic global</h3>
    <p>
      Imaginons que notre photographe publie un article très populaire sur un sujet éloigné de ses
      prestations.
    </p>
    <p>Il commence à recevoir beaucoup de visiteurs supplémentaires.</p>
    <p>Son trafic global augmente fortement.</p>
    <p>Mais aucune demande de devis supplémentaire n'apparaît.</p>
    <p>
      Cette progression peut tout de même présenter un intérêt de notoriété, selon ses objectifs.
    </p>
    <p>Mais elle ne doit pas être confondue avec une amélioration de l'acquisition commerciale.</p>
    <p>
      Il faut donc conserver une attention particulière aux pages et aux recherches qui
      correspondent réellement à ton activité.
    </p>
    <h3>Le piège de la position moyenne globale</h3>
    <p>
      Une autre erreur consiste à considérer la position moyenne globale comme une note générale du
      référencement.
    </p>
    <p>
      Nous avons vu qu'une page peut apparaître sur davantage de recherches et voir sa position
      moyenne évoluer sans que ses performances stratégiques se dégradent.
    </p>
    <p>
      Il est donc plus utile d'examiner certaines pages et requêtes importantes que de chercher à
      améliorer artificiellement une moyenne portant sur tout le site.
    </p>
    <h3>Le piège des indicateurs d'engagement</h3>
    <p>Dans Analytics, tu peux également rencontrer des indicateurs comme le taux d'engagement.</p>
    <p>
      Dans GA4, une session engagée correspond notamment à une session qui dure plus de dix
      secondes, comporte au moins deux pages ou écrans consultés, ou comprend un événement clé.
    </p>
    <p>Cet indicateur peut aider à comprendre certains comportements.</p>
    <p>Mais il ne doit pas être interprété comme une note absolue de qualité.</p>
    <p>
      Imaginons qu'une personne consulte un article pour vérifier une information simple, trouve
      immédiatement sa réponse et quitte le site.
    </p>
    <p>
      Cette visite peut avoir parfaitement répondu à son besoin, même si elle n'a pas parcouru
      plusieurs pages.
    </p>
    <p>
      À l'inverse, une longue session ne garantit pas que l'utilisateur a trouvé ce qu'il cherchait.
    </p>
    <p>Le contexte reste donc essentiel.</p>
