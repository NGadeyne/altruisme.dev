    <p>Examine maintenant les mots-clés qui semblent répondre à des besoins similaires.</p>
    <p>
      Si plusieurs expressions concernent exactement le même service ou une intention très proche,
      rassemble-les dans un groupe.
    </p>
    <p>
      À l'inverse, conserve des groupes distincts lorsque les attentes sont réellement différentes.
    </p>
    <p>
      Par exemple, une recherche destinée à trouver un professionnel et une recherche demandant des
      conseils pour choisir ce professionnel peuvent justifier deux contenus différents.
    </p>
    <p>Essaie de ne pas multiplier inutilement les groupes.</p>
    <p>Le but est de simplifier ton travail, pas de construire une organisation complexe.</p>
    <h3>Étape 4 — Associe chaque groupe à une page</h3>
    <p>Reprends les pages stratégiques que tu as identifiées à la fin du module 1.</p>
    <p>
      Pour chaque groupe de mots-clés, demande-toi si une page existante est capable de répondre
      correctement à l'intention de recherche.
    </p>
    <p>Si une page correspond déjà au besoin, note son adresse dans ton tableau.</p>
    <p>Si aucune page ne semble adaptée, indique simplement « À créer » ou « À étudier ».</p>
    <p>Ne crée pas encore de nouvelles pages et ne modifie pas les URL existantes.</p>
    <p>Nous allons d'abord terminer ce travail de préparation.</p>
    <h3>Étape 5 — Sélectionne tes trois premières priorités</h3>
