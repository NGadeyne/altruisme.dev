    </p>
    <p>
      Il reste une étape essentielle : déterminer quelle page de ton site doit répondre à chaque
      groupe de mots-clés.
    </p>
    <p>
      Cette démarche est parfois appelée <em>keyword mapping</em>, ou association des mots-clés aux
      pages.
    </p>
    <p>
      Son objectif est de construire une correspondance entre les besoins recherchés par les
      internautes et les contenus que ton site propose.
    </p>
    <p>Prenons un exemple.</p>
    <p>
      Imaginons que tu possèdes un site de conseil en référencement naturel. Tu proposes des audits
      SEO, un accompagnement à l'optimisation et plusieurs guides pédagogiques.
    </p>
    <p>
      Une recherche comme « consultant SEO Bordeaux » pourrait correspondre à une page présentant
      ton activité et tes prestations de conseil.
    </p>
    <p>
      Une recherche comme « audit SEO site internet » pourrait être associée à une page dédiée à
      cette prestation, si tu possèdes une offre spécifique et suffisamment distincte.
    </p>
    <p>
      Enfin, une recherche comme « pourquoi mon site n'est pas indexé sur Google » pourrait être
      traitée dans un guide expliquant les principaux problèmes d'indexation.
    </p>
    <p>
      Ces trois contenus appartiennent au même univers, mais ne répondent pas exactement au même
      besoin.
    </p>
    <p>L'association des mots-clés permet donc de clarifier le rôle de chaque page.</p>
    <h3>Commencer par les pages qui existent déjà</h3>
    <p>
      Lorsqu'on découvre un mot-clé intéressant, il peut être tentant de créer immédiatement une
      nouvelle page.
    </p>
    <p>Pourtant, ton site possède peut-être déjà un contenu capable de répondre au besoin.</p>
    <p>Imaginons que tu souhaites travailler « consultant SEO Bordeaux ».</p>
    <p>
      Si ta page d'accueil présente déjà clairement ton activité de conseil en référencement, tes
      prestations et ta zone d'intervention, elle pourrait constituer une page cible pertinente.
    </p>
    <p>
      Il ne serait pas forcément utile de créer une deuxième page presque identique uniquement pour
      y placer cette expression.
    </p>
    <p>
      À l'inverse, si tu proposes plusieurs services suffisamment différents, comme un audit
      ponctuel et un accompagnement SEO de longue durée, des pages dédiées peuvent aider à présenter
      chaque offre plus précisément.
    </p>
    <p>
      La décision dépend donc de la structure existante et des besoins que tu souhaites satisfaire.
    </p>
    <p>
      C'est pourquoi il est intéressant de commencer par inventorier tes pages principales avant
      d'en créer de nouvelles.
    </p>
    <p>
      <strong
        >Une nouvelle opportunité de mot-clé ne signifie pas automatiquement qu'il faut créer une
        nouvelle page.</strong
      >
    </p>
    <h3>Choisir une page principale pour chaque groupe</h3>
    <p>Pour faciliter ton travail, nous allons adopter une convention simple.</p>
    <p>Chaque groupe de recherches proches sera associé à une page cible principale.</p>
    <p>
      Par exemple, notre photographe pourrait regrouper plusieurs expressions liées à la
      photographie de mariage et les associer à une seule page présentant cette prestation.
    </p>
    <p>
      Dans son tableau, il pourrait distinguer une expression principale, utilisée comme repère pour
      décrire le sujet de la page, et quelques expressions secondaires qui correspondent à des
      formulations proches.
    </p>
    <p>L'expression principale ne représente pas un paramètre magique utilisé par Google.</p>
    <p>
      Il s'agit simplement d'une convention de travail qui t'aide à savoir quel sujet tu souhaites
      traiter en priorité.
    </p>
    <p>
      Google n'exige pas qu'une page possède un seul mot-clé, et une même page peut apparaître sur
      de nombreuses recherches différentes.
    </p>
    <p>
      L'objectif est de conserver une orientation claire pour le contenu, pas de limiter
      artificiellement sa visibilité à une seule expression.
    </p>
    <h3>Que faire lorsqu'aucune page ne correspond au besoin ?</h3>
    <p>
      Il est possible que certaines recherches intéressantes ne correspondent à aucun contenu
      existant sur ton site.
    </p>
    <p>
      Imaginons que notre photographe identifie « comment choisir son photographe de mariage » et
      qu'il ne possède aucun guide destiné à répondre à cette question.
    </p>
    <p>Il pourrait alors envisager de créer un article spécifique.</p>
    <p>Mais cette création ne doit pas nécessairement devenir une priorité immédiate.</p>
    <p>
      Avant de passer à l'action, il faudra vérifier que le sujet possède un intérêt réel pour son
      activité et qu'il pourra proposer une réponse utile.
    </p>
    <p>
      Pour le moment, nous pouvons simplement indiquer dans notre tableau qu'aucune page adaptée
      n'existe encore.
    </p>
    <p>Nous noterons alors « À créer » dans la colonne consacrée à la page cible.</p>
    <p>
      Cette distinction nous permettra de séparer deux types d'actions : améliorer les pages
      existantes et envisager de nouveaux contenus.
    </p>
    <p>Nous apprendrons à réaliser ces optimisations dans les prochains modules.</p>
