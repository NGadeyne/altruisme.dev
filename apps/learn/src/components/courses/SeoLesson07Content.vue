    </p>
    <p>
      Ces contenus pourraient se compléter, sans nécessairement chercher à répondre à toutes les
      intentions sur une seule page.
    </p>
    <h3>Ce que cette démonstration nous apprend</h3>
    <p>
      Nous venons d'observer trois recherches proches sur le plan thématique, mais différentes dans
      les attentes qu'elles peuvent traduire.
    </p>
    <p>
      Nous avons appris à examiner les mots utilisés, les types de résultats proposés par Google et
      les informations que les internautes pourraient rechercher.
    </p>
    <p>
      Nous avons également compris que l'intention n'est pas toujours évidente. Une même expression
