    </p>
    <p>
      <strong
        >Le rôle de l'analyse d'intention n'est pas de deviner parfaitement ce que pense chaque
        internaute. Il est de construire une hypothèse suffisamment pertinente pour proposer un
        contenu adapté.</strong
      >
    </p>
