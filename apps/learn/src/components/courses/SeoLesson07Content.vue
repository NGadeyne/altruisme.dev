      achat ou une réservation.
    </p>
    <p>
      Une personne peut rechercher une prestation, consulter plusieurs sites et finalement décider
      de reporter son projet.
    </p>
    <p>
      De même, certaines recherches présentent à la fois une dimension commerciale et
      transactionnelle.
    </p>
    <p>
      Par exemple, « prix création site internet professionnel » peut correspondre à une personne
      qui compare les budgets ou à quelqu'un qui cherche un prestataire capable de lui proposer un
      devis.
    </p>
    <p>
      Les catégories d'intentions restent donc des outils pour guider notre réflexion, pas des
      certitudes sur le comportement de chaque visiteur.
    </p>
