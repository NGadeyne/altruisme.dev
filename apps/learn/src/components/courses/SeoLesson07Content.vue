      professionnel ?
    </p>
    <p>
      Si les résultats proposent principalement des conseils, cela peut indiquer qu'une intention
      informationnelle occupe une place importante.
    </p>
    <p>
      Une personne effectuant cette recherche souhaite probablement obtenir des informations pour
      prendre une décision.
    </p>
    <p>
      Une page commerciale qui présente uniquement des tarifs et un formulaire de réservation
      pourrait donc ne pas répondre à toutes ses attentes.
    </p>
    <p>
      Pour notre photographe, un guide expliquant comment choisir un professionnel, avec des
      conseils issus de son expérience, pourrait constituer un contenu pertinent.
    </p>
