      et les informations d'achat pourrait être plus pertinente qu'un article général expliquant
      l'histoire du produit.
    </p>
    <p>
      Les recherches transactionnelles peuvent être particulièrement intéressantes pour une activité
      commerciale, car elles correspondent parfois à des personnes proches d'une décision.
    </p>
    <p>
