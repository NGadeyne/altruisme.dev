    <p>Effectue maintenant une deuxième recherche :</p>
    <p>`meilleur photographe mariage Bordeaux`</p>
    <p>
      Cette fois, l'internaute semble chercher à découvrir ou comparer plusieurs professionnels.
    </p>
    <p>Observe les résultats proposés par Google.</p>
    <p>
      Tu pourrais rencontrer des sites de photographes, des sélections de professionnels, des
