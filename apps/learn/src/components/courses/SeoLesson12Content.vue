    <h2>Ce qu'il faut retenir</h2>
    <p>
      La structure d'un site correspond à la manière dont ses différentes pages sont organisées.
    </p>
    <p>
      Une architecture logique facilite la navigation des visiteurs et peut aider les moteurs de
      recherche à comprendre les relations entre les contenus.
    </p>
    <p>
      Le maillage interne désigne les liens qui permettent de passer d'une page à une autre à
      l'intérieur du site.
    </p>
    <p>
      Ces liens peuvent contribuer à la découverte des pages, fournir des indications sur leur sujet
      et permettre aux visiteurs d'approfondir les informations qui les intéressent.
    </p>
    <p>
      Nous avons découvert plusieurs types de liens internes, notamment les liens de navigation, les
      liens contextuels et ceux qui présentent des contenus complémentaires.
    </p>
    <p>Leur intérêt dépend principalement de leur pertinence.</p>
    <p>
      Un lien bien placé doit aider le visiteur à accéder à une information utile et posséder un
      texte d'ancrage suffisamment descriptif pour présenter sa destination.
    </p>
    <p>
      Il n'existe pas de nombre idéal de liens à ajouter sur chaque page, ni d'obligation
      universelle consistant à rendre tous les contenus accessibles en trois clics.
    </p>
    <p>
      L'objectif est plutôt de construire des parcours logiques et de rendre les pages importantes
      suffisamment faciles à découvrir.
    </p>
    <p>
      Nous avons également appris qu'une page vers laquelle aucun lien interne ne pointe peut rester
      difficile à trouver, même si elle existe et peut être découverte par d'autres moyens.
    </p>
    <p>
      Enfin, il est important de vérifier régulièrement le fonctionnement des liens, notamment
      lorsque certaines pages sont déplacées ou supprimées.
    </p>
    <p>
      <strong
        >Un bon maillage interne ne sert pas uniquement ton référencement. Il permet surtout aux
        visiteurs de mieux comprendre ton site, de découvrir les contenus pertinents et de
        progresser naturellement dans leur parcours.</strong
      >
    </p>
    <p>
      Tu sais désormais comment améliorer une page individuellement et comment commencer à la relier
      au reste de ton site.
