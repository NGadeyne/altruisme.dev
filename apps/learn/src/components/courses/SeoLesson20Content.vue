      contenus sont utiles et son site fonctionne correctement. Mais aucun autre site ne parle
      encore de son activité. À l'inverse, un photographe concurrent est régulièrement cité par des
      lieux de réception, des organisateurs de mariage et plusieurs publications spécialisées.
      Certains de ces sites proposent également un lien vers son portfolio.
    </p>
    <p>
      Ces mentions peuvent permettre à de futurs clients de découvrir son travail. Elles peuvent
      aussi aider les moteurs de recherche à comprendre que ses pages sont connues et citées dans un
      environnement pertinent. Cela ne signifie pas que le concurrent obtiendra automatiquement de
      meilleures positions : le référencement dépend de nombreux éléments, notamment de la
      pertinence des contenus et de l'intention de recherche. Mais cet exemple illustre une
      dimension que nous n'avons pas encore étudiée : les relations entre ton site et les autres
      sites présents sur Internet.
    </p>
    <p>
      <strong
        >Le référencement naturel ne dépend pas uniquement de ce que tu publies sur ton propre site.
        Il dépend également, entre autres, de la manière dont tes contenus sont découverts, cités et
        reliés depuis le reste du Web.</strong
      >
      Dans les modules précédents, nous avons appris à améliorer ce que tu contrôles directement :
      tes pages, tes contenus, ton architecture et tes paramètres techniques. Nous allons maintenant
      découvrir le rôle des liens provenant d'autres domaines, généralement appelés
      <em>backlinks</em>. L'objectif de cette première leçon n'est pas encore de rechercher des
      partenaires ou de lancer une campagne de netlinking. Nous allons d'abord comprendre pourquoi
      les liens existent, comment ils peuvent être interprétés par Google et ce qui différencie un
      lien réellement pertinent d'un lien créé uniquement pour influencer les classements.
    </p>
    <h2>Comprendre ce qu'est un backlink</h2>
    <p>
      Un backlink est un lien présent sur une page d'un autre site et qui dirige vers une page de
      ton propre site. On parle également de lien entrant ou de lien externe entrant. Imaginons
      qu'un site spécialisé dans l'organisation de mariages publie un guide consacré aux
      prestataires de la région bordelaise. Dans une section sur la photographie, il présente le
      travail de notre photographe et propose un lien vers son site. Ce lien est un backlink pour
      notre photographe : il permet à une personne qui consulte le guide de découvrir directement
      son activité.
    </p>
    <p>
      La distinction avec le maillage interne est importante. Dans la leçon 12, nous avons appris à
      créer des liens entre les pages d'un même site afin de faciliter la navigation, de relier des
      contenus complémentaires et d'aider Google à découvrir les différentes ressources. Un
      backlink, en revanche, provient d'un autre site. Il crée donc une relation entre deux domaines
      ou propriétés distincts. Dans les deux cas, le lien permet à un visiteur de passer d'une page
      à une autre. Mais les backlinks possèdent une particularité : ils peuvent refléter le choix
      d'un tiers de citer une ressource extérieure à son propre site.
    </p>
    <p>
      Pour comprendre leur intérêt, il faut se rappeler que les liens existaient bien avant les
      stratégies modernes de référencement. Le Web repose notamment sur la possibilité de relier des
      documents entre eux. Lorsqu'un auteur souhaite mentionner une source, recommander un outil,
      citer une étude ou présenter le travail d'une entreprise, il peut naturellement créer un lien
      vers la ressource concernée. Imaginons que notre photographe réalise les images d'un mariage
      organisé dans un château près de Bordeaux. Le propriétaire du lieu souhaite présenter cet
      événement sur son site. Il publie un article, ajoute quelques photographies utilisées avec
      autorisation et mentionne les professionnels qui ont participé à sa réalisation. Il peut alors
      proposer un lien vers le portfolio de notre photographe. Ce lien possède une justification
      naturelle : il permet au lecteur de découvrir la personne qui a réalisé les photographies.
    </p>
    <p>
      De la même manière, un média local pourrait citer notre photographe dans un article consacré à
      une exposition. Une association professionnelle pourrait présenter son activité parmi ses
      membres. Un autre professionnel pourrait recommander un guide particulièrement utile qu'il a
      publié. Dans chacune de ces situations, le lien ne sert pas uniquement au référencement : il
      apporte une information complémentaire au lecteur.
    </p>
    <p>
      <strong
        >Un bon backlink commence donc souvent par une raison simple : quelqu'un considère qu'une
        ressource mérite d'être mentionnée ou découverte.</strong
      >
      C'est cette logique qu'il faut comprendre avant de chercher à développer une stratégie de
      liens entrants.
    </p>
    <h2>Pourquoi Google tient-il compte des liens ?</h2>
    <p>
      Pour comprendre l'intérêt des backlinks, il est utile de revenir brièvement à l'histoire de
      Google. Dès ses débuts, Google a développé des systèmes permettant notamment d'analyser les
      relations entre les pages du Web. L'un des plus connus est PageRank. Son principe historique
      repose sur l'idée que les liens peuvent fournir des informations sur l'importance relative des
      pages. Une page recevant des liens provenant d'autres ressources peut ainsi être considérée
      différemment d'une page totalement isolée.
    </p>
    <p>
      Mais ce principe doit être compris avec prudence. PageRank ne se résume pas à compter le
      nombre de liens reçus. Le fonctionnement moderne de Google a considérablement évolué et ses
      systèmes utilisent de nombreux autres signaux pour comprendre les contenus et sélectionner les
      résultats. Google confirme néanmoins que l'analyse des liens et PageRank continuent de faire
      partie de ses systèmes de classement. Les liens peuvent notamment aider à comprendre les
      relations entre les pages et à identifier des ressources susceptibles d'être utiles pour une
      recherche.
    </p>
    <p>
      Imaginons que plusieurs sites consacrés à l'organisation de mariages citent un guide publié
      par notre photographe. Cette situation peut contribuer à montrer que la ressource possède une
      place dans un ensemble de contenus traitant du mariage. Mais Google ne considère pas
      nécessairement tous les liens comme des recommandations équivalentes. Certains peuvent être
      créés automatiquement, d'autres peuvent correspondre à des publicités et certains peuvent
      avoir été placés principalement pour manipuler les résultats de recherche. Il serait donc
      incorrect de considérer qu'un backlink supplémentaire entraîne mécaniquement une progression
      de position.
    </p>
    <p>
      Il est intéressant de distinguer trois bénéfices possibles d'un lien entrant. Le premier
      concerne la <strong>découverte</strong> : un backlink permet aux internautes de passer d'un
      autre site vers le tien et peut également constituer un chemin de découverte pour les robots
      qui suivent les liens. Le deuxième concerne la <strong>notoriété</strong> : lorsqu'un média,
      un partenaire ou un professionnel pertinent cite ton activité, de nouvelles personnes peuvent
      découvrir ton entreprise. Enfin, le troisième concerne le <strong>référencement</strong> :
      selon ses caractéristiques et la manière dont il est interprété par Google, un lien peut faire
      partie des signaux utilisés pour analyser les relations entre les pages.
    </p>
    <p>
      Ces bénéfices ne sont pas systématiques. Un lien peut ne générer aucune visite, être ignoré
      pour certains traitements liés au classement ou ne produire aucun effet mesurable sur tes
      positions. Mais cette distinction permet de comprendre pourquoi les backlinks ne doivent pas
      être envisagés uniquement comme des points à accumuler dans un outil SEO. Un lien peut
      posséder un intérêt commercial ou éditorial réel, même lorsque son effet précis sur le
      classement est impossible à déterminer.
    </p>
    <h2>Comprendre ce que signifie l'autorité d'un site</h2>
    <p>
      Dans le domaine du SEO, tu rencontreras très souvent le terme <em>autorité</em>. On parle
      notamment d'autorité de domaine, d'autorité d'une page ou de popularité d'un site. Dans un
      sens général, l'autorité désigne l'idée qu'un site ou une ressource bénéficie d'une certaine
      reconnaissance, d'une crédibilité ou d'une importance dans son domaine. Imaginons qu'un guide
      consacré aux métiers du mariage soit régulièrement cité par des professionnels, des
      associations et des publications spécialisées. Ces références peuvent contribuer à sa
      reconnaissance dans son environnement. À l'inverse, un site récemment créé peut encore être
      peu connu, même lorsqu'il propose d'excellents contenus.
    </p>
    <p>
      Cette différence de notoriété peut aider à comprendre certaines situations de concurrence.
      Mais il faut éviter une confusion importante :
      <strong
        >Google ne publie pas une note universelle d'autorité de domaine permettant de connaître
        précisément la force SEO d'un site</strong
      >. Il utilise différents systèmes et signaux, à l'échelle des pages et parfois du site, mais
      ne fournit pas un score public unique que les propriétaires pourraient optimiser directement.
    </p>
    <p>
      Il faut également distinguer l'autorité de l'expertise. Imaginons que notre photographe
      possède quinze années d'expérience dans son métier. Il maîtrise parfaitement la photographie
      de mariage, connaît les contraintes des reportages et possède de nombreuses réalisations. Son
      expertise professionnelle est réelle, mais cela ne signifie pas que son site possède déjà de
      nombreux backlinks. À l'inverse, une grande plateforme spécialisée dans l'organisation de
      mariages peut recevoir énormément de liens sans posséder nécessairement une expertise plus
      approfondie sur chaque aspect de la photographie.
    </p>
    <p>
      Ces dimensions peuvent se compléter, mais elles ne sont pas identiques. L'expertise correspond
      aux connaissances et aux compétences que tu peux démontrer. La notoriété et les liens
      reflètent notamment la manière dont ton travail est découvert, mentionné ou recommandé par
      d'autres. Dans les modules précédents, nous avons également abordé les notions d'expérience,
      d'expertise, d'autorité et de fiabilité à travers le modèle E-E-A-T utilisé dans les
      recommandations de Google. Ce cadre permet de réfléchir aux qualités attendues d'un contenu,
      mais il ne correspond pas à un facteur de classement unique auquel Google attribuerait
      directement une note.
    </p>
    <p>
      Un site ne devient donc pas automatiquement fiable parce qu'il possède un grand nombre de
      backlinks. La qualité des informations, la transparence, la pertinence du contenu et les
      autres éléments de l'expérience restent essentiels.
    </p>
    <h2>Comprendre les scores DR, DA et Trust Flow</h2>
    <p>
      Si tu utilises un outil SEO, tu rencontreras probablement plusieurs indicateurs destinés à
      estimer la popularité ou la force d'un domaine. Parmi les plus connus figurent le
      <em>Domain Rating</em> d'Ahrefs, le <em>Domain Authority</em> de Moz et le
      <em>Trust Flow</em> de Majestic. Ces indicateurs peuvent être utiles pour comparer des sites
      ou examiner leur profil de liens. Mais une distinction fondamentale doit être retenue :
      <strong
        >ce sont des métriques créées par des entreprises privées, et non des notes attribuées par
        Google</strong
      >.
    </p>
    <p>
      Le Domain Rating, souvent abrégé en DR, est utilisé par Ahrefs pour représenter la force
      relative du profil de backlinks d'un domaine selon son propre modèle. Le Domain Authority, ou
      DA, est une métrique développée par Moz pour estimer la capacité potentielle d'un domaine à se
      positionner dans les résultats de recherche, selon sa méthodologie. Le Trust Flow, ou TF, est
      proposé par Majestic pour évaluer certains aspects de la qualité du profil de liens, notamment
      à partir de relations avec des sites de référence dans son modèle. Majestic propose également
      le Citation Flow, qui cherche à mesurer certains aspects de l'influence des liens.
    </p>
    <p>
      Ces scores ne mesurent donc pas exactement la même chose. Ils reposent sur des données, des
      calculs et des méthodes propres à chaque fournisseur. Deux outils peuvent parfaitement donner
      des appréciations différentes sur un même domaine. Imaginons que notre photographe examine son
      site et découvre un Domain Rating de 8. Il pourrait penser que son référencement est mauvais
      et qu'il doit absolument atteindre un DR de 30 ou de 50 avant de pouvoir apparaître dans
      Google. Ce raisonnement serait incorrect.
    </p>
    <p>
      Un DR faible peut notamment correspondre à un site récent ou à un domaine possédant encore peu
      de liens détectés par Ahrefs. Mais il ne permet pas de conclure que toutes les pages du site
      sont incapables de se positionner. Une page locale particulièrement pertinente peut apparaître
      sur des recherches ciblées, même lorsque le domaine possède un profil de liens limité. À
      l'inverse, un site affichant un DR très élevé ne sera pas automatiquement bien positionné sur
      toutes les recherches. S'il ne possède aucun contenu réellement adapté à une intention donnée,
      son score ne suffira pas à compenser ce manque de pertinence.
    </p>
    <p>
      Il n'existe donc pas de seuil de DR, de DA ou de TF à atteindre pour que Google commence à
      considérer ton site comme sérieux. Ces indicateurs peuvent servir de repères comparatifs, mais
      ils ne doivent pas devenir des objectifs commerciaux ou éditoriaux à eux seuls.
    </p>
    <p>
      Prenons un dernier exemple. Notre photographe a la possibilité d'être mentionné sur deux
      sites. Le premier possède un DR élevé, mais traite de sujets sans rapport avec son activité.
      Le deuxième est un blog local consacré à l'organisation de mariages, avec un DR beaucoup plus
      modeste. Il serait trop simpliste de choisir automatiquement le premier. Le blog spécialisé
      peut présenter un véritable intérêt grâce à son public, son contexte éditorial et la
      pertinence de la mention. Cela ne signifie pas qu'un lien thématiquement proche possède
      toujours davantage de valeur SEO qu'un lien provenant d'un grand média généraliste. Mais cela
      montre pourquoi un score ne doit jamais remplacer l'analyse.
    </p>
    <p>
      <strong
        >Un indicateur d'autorité peut t'aider à examiner un site. Il ne peut pas décider à lui seul
        si un lien mérite d'exister.</strong
      >
    </p>
    <h2>Pourquoi tous les backlinks n'ont-ils pas la même valeur ?</h2>
    <p>
      Deux backlinks peuvent pointer vers la même page sans présenter le même intérêt. Leur
      contexte, leur origine, leur emplacement, leur destination et leur nature peuvent différer
      considérablement. Imaginons que notre photographe reçoive un lien depuis un article consacré à
      l'organisation d'un mariage en Gironde. L'auteur présente plusieurs prestataires locaux et
      recommande son portfolio dans une section consacrée à la photographie. Ce lien possède un
      contexte clair : le lecteur comprend pourquoi le photographe est mentionné et peut consulter
      son travail s'il le souhaite.
    </p>
    <p>
      Imaginons maintenant un autre lien publié dans une longue liste de plusieurs centaines de
      sites sans rapport entre eux. Aucune explication ne présente le photographe, et le lien semble
      avoir été ajouté uniquement pour augmenter artificiellement le nombre de références. Les deux
      liens existent techniquement, mais leur intérêt pour le lecteur et leur justification
      éditoriale sont très différents.
    </p>
    <p>
      Le premier élément à examiner est donc la <strong>pertinence du contexte</strong>. Un site
      consacré aux lieux de réception peut naturellement avoir une raison de citer un photographe de
      mariage. De même, un média local peut présenter un professionnel installé dans sa région.
      Cette pertinence ne doit toutefois pas être interprétée de manière trop rigide : notre
      photographe pourrait recevoir un lien parfaitement légitime depuis un journal national ou un
      site culturel à l'occasion d'une exposition. L'important est de comprendre pourquoi la page
      source mentionne la ressource.
    </p>
    <p>
      Le deuxième élément concerne la qualité du site et de la page d'origine. Présente-t-elle un
      contenu réel, compréhensible et utile ? L'auteur semble-t-il avoir une raison légitime de
      citer ton activité ? La page est-elle cohérente avec le sujet abordé ? Il ne s'agit pas de
      déterminer si le site possède une apparence suffisamment haut de gamme. Un petit blog
      spécialisé peut proposer des informations excellentes, tandis qu'un site possédant une
      apparence très professionnelle peut publier des contenus superficiels.
    </p>
    <p>
      Le troisième élément concerne la destination du lien. Un backlink peut renvoyer vers la page
      d'accueil de ton site, mais aussi vers une prestation, un guide ou une ressource particulière.
      Si un lieu de réception publie un reportage photographique réalisé par notre professionnel, un
      lien vers son portfolio consacré aux mariages peut être particulièrement utile. En revanche,
      lorsqu'une publication présente simplement son entreprise, un lien vers sa page d'accueil peut
      parfaitement convenir. Il n'existe pas de destination universelle à privilégier : le lien doit
      permettre d'accéder à la ressource attendue.
    </p>
    <p>
      Enfin, le texte d'ancrage mérite également une attention particulière. Nous avons découvert
      son rôle pour les liens internes dans la leçon 12, mais le même principe s'applique aux
      backlinks. Un article peut naturellement proposer un lien sur le nom professionnel de notre
      photographe ou sur une expression décrivant son travail. Il n'est pas nécessaire que tous les
      liens utilisent exactement le même mot-clé. Chercher à imposer systématiquement une expression
      commerciale identique dans des dizaines de liens peut même constituer une pratique
      artificielle.
    </p>
    <p>
      Une question simple permet souvent de commencer cette analyse :
      <strong
        >si Google n'existait pas, ce lien aurait-il encore une raison d'être pour les personnes qui
        consultent la page ?</strong
      >
      Si la réponse est oui, il possède probablement une justification éditoriale compréhensible.
      Cela ne permet pas de prédire son effet SEO, mais constitue un premier critère utile.
    </p>
    <h2>Comprendre les domaines référents</h2>
    <p>
      Lorsque tu examines des backlinks, tu rencontres également la notion de
      <em>domaine référent</em>. Un domaine référent correspond à un domaine depuis lequel au moins
      un lien vers ton site a été identifié par l'outil utilisé. Cette notion permet de distinguer
      le nombre de liens reçus du nombre de domaines différents qui les proposent.
    </p>
    <p>
      Imaginons que notre photographe possède dix backlinks provenant d'un seul site. Ces dix liens
      peuvent apparaître sur plusieurs pages du même domaine. Dans un autre cas, il possède dix
      backlinks provenant de dix domaines différents. Les deux situations correspondent au même
      nombre de liens, mais pas au même nombre de domaines référents. Cette distinction peut être
      intéressante pour comprendre la diversité des sites qui mentionnent ton activité.
    </p>
    <p>
      Mais il faut éviter d'en déduire une formule automatique. Dix domaines référents ne
      garantissent pas une meilleure visibilité qu'un seul domaine référent. Certains liens peuvent
      être artificiels, peu pertinents ou provenir de ressources de faible qualité. À l'inverse,
      plusieurs liens depuis un même site ne sont pas nécessairement problématiques lorsqu'ils
      répondent à des besoins éditoriaux légitimes.
    </p>
    <p>
      Tu pourrais également constater qu'Ahrefs, Semrush, Majestic et Google Search Console
      n'affichent pas exactement les mêmes chiffres. Cette différence est normale : chaque
      fournisseur possède ses propres méthodes de découverte, d'exploration, de regroupement et de
      traitement des liens. Un outil peut connaître une page qu'un autre n'a pas encore explorée.
      Certains liens peuvent avoir été supprimés, tandis que plusieurs URL peuvent être regroupées
      lorsqu'elles correspondent à un même contenu.
    </p>
    <p>
      Google Search Console précise d'ailleurs que son rapport sur les liens ne constitue pas une
      liste exhaustive de tous les backlinks connus. Il présente des informations destinées à aider
      les propriétaires de sites à comprendre leur profil de liens. Tu ne dois donc pas chercher à
      obtenir un chiffre parfaitement identique dans tous les outils.
    </p>
    <p>
      L'important est de comprendre ce que chaque donnée représente et de ne pas transformer une
      estimation en certitude.
    </p>
    <h2>Comprendre les liens nofollow, sponsored et ugc</h2>
    <p>
      Tous les backlinks ne transmettent pas exactement les mêmes indications aux moteurs de
      recherche. Certains contiennent des attributs techniques permettant de préciser leur nature.
      Tu rencontreras principalement les valeurs <code>nofollow</code>, <code>sponsored</code> et
      <code>ugc</code>. Tu n'as pas besoin de savoir les configurer immédiatement, mais il est utile
      de comprendre leur rôle.
    </p>
    <p>
      L'attribut <code>rel="nofollow"</code> permet notamment d'indiquer à Google que le
      propriétaire de la page ne souhaite pas cautionner de la même manière la destination du lien.
      Google traite cet attribut comme un indice dans ses systèmes, et non comme une règle absolue
      déterminant à elle seule tous les traitements possibles. Cela ne signifie pas qu'un lien
      <code>nofollow</code> est automatiquement inutile : il peut toujours permettre à des visiteurs
      de découvrir ton activité.
    </p>
    <p>
      L'attribut <code>rel="sponsored"</code> sert à identifier les liens provenant notamment de
      publicités, de sponsorings ou d'autres accords commerciaux. Imaginons qu'une publication
      présente notre photographe dans le cadre d'un partenariat rémunéré. Si le lien est
      publicitaire, il doit être correctement qualifié afin de ne pas être utilisé pour transmettre
      artificiellement des signaux de classement. Google recommande notamment l'utilisation de
      <code>sponsored</code> dans ce contexte.
    </p>
    <p>
      Enfin, l'attribut <code>rel="ugc"</code> concerne principalement les liens présents dans les
      contenus générés par les utilisateurs, comme certains commentaires de blog ou messages publiés
      sur des forums. Si un internaute recommande notre photographe dans une discussion publique, le
      lien peut posséder cet attribut selon la configuration de la plateforme. Cela ne signifie pas
      que la recommandation est fausse ou sans intérêt : il s'agit d'une indication technique sur la
      nature du lien.
    </p>
    <p>
      <strong
        >Il ne faut donc pas opposer artificiellement les liens utiles et inutiles selon un seul
        attribut.</strong
      >
      Leur contexte, leur pertinence et leur objectif réel restent essentiels à comprendre.
    </p>
    <h2>Pourquoi l'achat de backlinks peut poser problème</h2>
    <p>
      Lorsqu'un entrepreneur découvre l'importance des backlinks, il peut être tenté de chercher un
      moyen d'en obtenir rapidement. Certaines offres promettent plusieurs dizaines ou centaines de
      liens pour un tarif relativement faible. D'autres proposent la publication d'articles sur des
      sites affichant des métriques élevées, avec la possibilité de choisir précisément les
      mots-clés utilisés dans les liens. Ces pratiques peuvent sembler intéressantes lorsqu'on
      cherche à développer rapidement sa visibilité, mais il faut en comprendre les risques.
    </p>
    <p>
      Google considère notamment comme du spam de liens les pratiques consistant à acheter ou vendre
      des liens dans le but de manipuler les classements. Cela peut également concerner des échanges
      excessifs, des réseaux de sites créés principalement pour produire des backlinks ou des liens
      publiés automatiquement à grande échelle. Certaines pratiques peuvent être ignorées par les
      systèmes de Google, tandis que des violations des règles peuvent entraîner une perte de
      visibilité ou des actions manuelles.
    </p>
    <p>
      Le fait qu'un site possède un DR élevé ou qu'un vendeur promette un lien permanent ne garantit
      donc ni son intérêt SEO ni sa conformité aux règles. Il ne faut pas non plus penser qu'une
      stratégie de netlinking doit nécessairement commencer par l'achat de liens.
    </p>
    <p>
      Une entreprise peut développer sa présence grâce à des contenus utiles, des collaborations
      légitimes, des références professionnelles ou des publications qui possèdent un intérêt
      indépendant du référencement. La publicité et les partenariats rémunérés peuvent également
      être parfaitement légitimes lorsqu'ils sont transparents et que les liens concernés sont
      correctement qualifiés. Le problème apparaît lorsqu'ils servent à manipuler artificiellement
      les résultats Google.
    </p>
    <p>
      Nous apprendrons à rechercher des opportunités pertinentes dans la prochaine leçon, puis à
      reconnaître les pratiques problématiques dans la leçon 22. Pour le moment, retiens que
      <strong
        >la valeur d'un backlink ne dépend pas uniquement de son prix, de son nombre ou de la note
        affichée par le site qui le propose</strong
      >.
    </p>
    <h2>Un site récent peut-il se positionner sans backlinks ?</h2>
    <p>
      C'est une question fréquente lorsqu'on commence à travailler son référencement. Imaginons que
      tu viennes de créer un site vitrine pour une activité locale. Tu possèdes cinq pages de
      qualité, une bonne organisation technique et aucun backlink identifié. Faut-il attendre
      d'obtenir plusieurs dizaines de domaines référents avant d'espérer apparaître dans Google ?
    </p>
    <p>
      Non. Les backlinks peuvent contribuer au référencement, mais ils ne représentent pas une
      condition préalable universelle à l'indexation ou au classement. Un site peut apparaître sur
      certaines recherches pertinentes même s'il possède encore peu de liens entrants. Cela dépend
      notamment de l'intention de recherche, de la concurrence, de la pertinence de la page et des
      autres éléments pris en compte par les systèmes de Google.
    </p>
    <p>
      Certaines recherches sont très concurrentielles et impliquent des sites bénéficiant déjà d'une
      forte reconnaissance. D'autres correspondent à des besoins locaux ou particulièrement
      spécifiques sur lesquels un site récent peut proposer une réponse adaptée. Il serait donc
      trompeur d'affirmer qu'un site doit atteindre un DR de 20, 30 ou 50 avant de pouvoir se
      positionner. Mais il serait tout aussi incorrect de prétendre que les liens ne jouent plus
      aucun rôle.
    </p>
    <p>
      La bonne approche consiste à travailler progressivement plusieurs dimensions complémentaires.
      Tu peux continuer à améliorer tes contenus, ton référencement technique et ton maillage
      interne tout en développant la notoriété de ton activité. Ces efforts ne doivent pas
      nécessairement être réalisés les uns après les autres : ils peuvent progresser ensemble, selon
      tes ressources et tes priorités.
    </p>
    <h2>Découvrir ses premiers backlinks avec Google Search Console</h2>
    <p>
      Pour comprendre ton profil de liens, tu n'as pas nécessairement besoin d'un abonnement à un
      outil spécialisé. Google Search Console possède un rapport consacré aux liens. Lorsque tu
      sélectionnes la propriété correspondant à ton site, tu peux accéder à la section « Liens »
      pour consulter les informations disponibles.
    </p>
    <p>
      Le rapport distingue notamment les liens internes et externes. Les liens externes permettent
      de découvrir certaines pages de ton site qui reçoivent des backlinks, les domaines qui
      proposent des liens vers tes contenus et les textes d'ancrage identifiés. Ces informations
      constituent un bon point de départ pour comprendre ta situation.
    </p>
    <p>
      Imaginons que notre photographe ouvre son rapport et découvre plusieurs domaines. Il remarque
      notamment le site d'un lieu de réception, celui d'une association locale et une publication
      consacrée à un événement auquel il a participé. Ces informations peuvent lui permettre de
      comprendre où son activité est déjà mentionnée. Il peut ensuite consulter certaines pages
      d'origine pour examiner le contexte des liens. Le contenu présente-t-il réellement son travail
      ? Le lien dirige-t-il vers une page pertinente ? La mention possède-t-elle une justification
      claire ?
    </p>
    <p>
      Le rapport peut également montrer quelles pages de ton site sont les plus souvent citées.
      Imaginons que notre photographe découvre que plusieurs liens renvoient vers sa page d'accueil,
      tandis que son guide sur le choix d'un professionnel ne possède encore aucune référence
      identifiée. Cela ne constitue pas nécessairement un problème. Mais cette information peut
      l'aider à comprendre quels contenus attirent déjà l'attention en dehors de son site.
    </p>
    <p>
      Si ton site est récent ou peu connu, le rapport peut présenter très peu d'informations. Il est
      également possible que certains liens existants n'apparaissent pas dans les données affichées.
      Rappelle-toi que Search Console ne fournit pas un inventaire exhaustif de tous les backlinks.
      L'absence de liens dans le rapport ne permet donc pas de prouver que personne n'a jamais
      mentionné ton site.
    </p>
    <p>
      Si tu ne disposes d'aucune référence identifiable, ce n'est pas une raison pour chercher
      immédiatement une solution artificielle. Tu possèdes simplement un point de départ. La suite
      consistera à identifier des relations, des ressources et des opportunités pertinentes pour
      développer progressivement la visibilité de ton activité.
    </p>
    <h2>Démonstration — Comparons plusieurs backlinks vers notre photographe</h2>
    <p>
      Passons maintenant à une démonstration concrète. Nous allons reprendre notre photographe
      professionnel à Bordeaux et imaginer qu'il découvre plusieurs liens pointant vers son site.
      Notre objectif n'est pas de calculer leur valeur SEO exacte, puisque aucun outil ne permet de
      garantir précisément le gain de classement associé à chaque backlink. Nous allons plutôt
      apprendre à examiner leur contexte, leur pertinence et leur utilité potentielle.
    </p>
    <p>Les domaines, les scores et les situations présentés dans cet exemple sont fictifs.</p>
    <h3>Étape 1 — Identifier les liens reçus</h3>
    <p>
      Imaginons que notre photographe découvre trois backlinks. Le premier provient d'un blog local
      consacré à l'organisation de mariages en Gironde. Un article présente plusieurs lieux de
      réception et recommande son portfolio pour illustrer le travail d'un photographe
      professionnel. Le deuxième provient d'un site généraliste qui présente une longue liste
      d'entreprises sans rapport entre elles. Son nom apparaît parmi plusieurs centaines de liens,
      sans description particulière. Enfin, le troisième provient d'un média régional ayant publié
      un article sur une exposition photographique à laquelle il a participé.
    </p>
    <p>
      Ces trois liens renvoient vers son site, mais ils ne possèdent pas le même contexte. Nous
      allons maintenant examiner les raisons pour lesquelles ils ont été créés et les ressources
      auxquelles ils permettent d'accéder.
    </p>
    <h3>Étape 2 — Examiner la pertinence des différentes sources</h3>
    <p>
      Commençons par le blog consacré aux mariages. Le site traite de sujets proches de l'activité
      de notre photographe et son article propose des conseils aux futurs mariés. Le lien vers le
      portfolio possède donc une justification claire : une personne intéressée par l'organisation
      de son mariage pourrait naturellement consulter son travail. Ce backlink peut représenter une
      opportunité de découverte auprès d'un public pertinent, sans que nous puissions affirmer qu'il
      entraînera automatiquement une progression dans Google.
    </p>
    <p>
      Passons maintenant au site généraliste. Il possède de nombreuses pages et affiche, dans notre
      exemple fictif, un score d'autorité relativement élevé dans certains outils. Mais la page
      contenant le lien ne présente aucune information sur notre photographe. Elle regroupe
      plusieurs centaines de références sans contexte et semble principalement destinée à accumuler
      des liens. Nous pouvons donc nous interroger sur son intérêt réel. Un visiteur possède-t-il
      une raison particulière de cliquer ? La mention apporte-t-elle une information utile ? Le lien
      a-t-il été placé dans un contexte éditorial cohérent ? Si les réponses sont négatives, le
      score du domaine ne suffit pas à rendre ce backlink intéressant.
    </p>
    <p>
      Enfin, examinons la mention du média régional. Son article présente une exposition
      photographique à laquelle notre professionnel a réellement participé. Le sujet n'est pas
      directement lié aux mariages, mais la référence possède une justification : le média permet
      aux lecteurs de découvrir le travail d'un artiste participant à l'événement. Ce lien peut donc
      contribuer à sa visibilité et à sa notoriété.
    </p>
    <p>
      Cette comparaison nous apprend qu'un backlink pertinent ne provient pas nécessairement d'un
      site traitant exactement du même mot-clé. Il peut aussi être légitime parce qu'il présente une
      activité, cite une réalisation ou complète une information.
    </p>
    <h3>Étape 3 — Comparer les liens sans se limiter aux métriques</h3>
    <p>
      Imaginons maintenant que les trois domaines affichent les scores suivants dans un outil SEO :
    </p>
    <div class="mt-6 overflow-x-auto rounded-xl border border-petrol/15">
      <table class="w-full min-w-[560px] border-collapse text-left text-sm">
        <thead class="bg-mist text-ink">
          <tr>
            <th scope="col" class="px-4 py-3 font-semibold">Source fictive</th>
            <th scope="col" class="px-4 py-3 font-semibold">DR fictif</th>
            <th scope="col" class="px-4 py-3 font-semibold">Contexte</th>
          </tr>
        </thead>
        <tbody class="divide-y divide-petrol/10">
          <tr>
            <td class="px-4 py-3">Blog de mariage local</td>
            <td class="px-4 py-3">18</td>
            <td class="px-4 py-3">Recommandation pertinente dans un guide spécialisé</td>
          </tr>
          <tr>
            <td class="px-4 py-3">Site généraliste de liens</td>
            <td class="px-4 py-3">65</td>
            <td class="px-4 py-3">Liste de centaines de liens sans explication</td>
          </tr>
          <tr>
            <td class="px-4 py-3">Média régional</td>
            <td class="px-4 py-3">42</td>
            <td class="px-4 py-3">Article consacré à une exposition réelle</td>
          </tr>
        </tbody>
      </table>
    </div>
    <p>
      Si nous nous contentions de classer ces domaines selon leur DR, le site généraliste arriverait
      en première position. Mais notre analyse éditoriale nous conduit à une autre lecture. Le blog
      de mariage peut présenter un intérêt commercial particulier, puisqu'il touche un public proche
      des futurs clients du photographe. Le média régional peut contribuer à sa notoriété et à la
      découverte de son travail. Le site généraliste, malgré son score supérieur, ne semble apporter
      aucune recommandation clairement justifiée.
    </p>
    <p>
      Nous ne pouvons pas calculer lequel des trois liens aura le plus d'effet sur les classements
      Google. En revanche, nous pouvons identifier ceux qui possèdent une valeur compréhensible pour
      les lecteurs. C'est pourquoi les métriques doivent rester des informations complémentaires, et
      non devenir le seul critère de décision.
    </p>
    <h3>Étape 4 — Examiner la destination des liens</h3>
    <p>
      Nous allons maintenant vérifier les pages vers lesquelles ces liens dirigent. Imaginons que le
      blog de mariage renvoie directement vers le portfolio consacré aux reportages. Cette
      destination paraît cohérente avec les informations présentées dans l'article. Le média
      régional renvoie vers la page d'accueil, qui permet de découvrir l'ensemble du travail du
      photographe. Cette destination peut également être pertinente.
    </p>
    <p>
      Le site généraliste, quant à lui, dirige vers une ancienne URL désormais supprimée. Le lien ne
      permet donc plus d'accéder correctement au contenu attendu. Nous avons identifié une
      difficulté technique potentielle. S'il existe une nouvelle page équivalente à l'ancienne, une
      redirection permanente appropriée pourrait permettre de préserver l'accès à la ressource. En
      revanche, il ne serait pas nécessaire de rediriger une URL supprimée vers une page sans
      rapport uniquement pour récupérer un backlink.
    </p>
    <p>
      Cette vérification montre que les notions étudiées dans les modules précédents restent utiles
      pour comprendre les liens externes. La pertinence d'un backlink dépend aussi de l'expérience
      proposée à la personne qui l'utilise.
    </p>
    <h3>Étape 5 — Tirer les premières conclusions</h3>
    <p>
      Après cette analyse, notre photographe possède une vision plus claire de son profil de liens.
      Il comprend que certaines références peuvent présenter une véritable valeur éditoriale,
      commerciale ou de notoriété. Il sait également que le nombre de backlinks et les scores
      d'autorité ne suffisent pas à évaluer la pertinence d'une référence. Enfin, il découvre
      l'intérêt de vérifier les pages de destination et le contexte dans lequel les liens sont
      publiés.
    </p>
    <p>
      Nous n'avons pas encore cherché à obtenir de nouveaux liens, mais nous disposons désormais des
      critères nécessaires pour reconnaître des références intéressantes.
    </p>
    <p>
      <strong
        >Le bon réflexe n'est pas de chercher les domaines qui affichent les plus gros chiffres. Il
        est de comprendre pourquoi quelqu'un aurait une raison légitime de recommander ton
        contenu.</strong
      >
    </p>
    <h2>À toi de jouer — Découvre ton profil de backlinks</h2>
    <p>
      Nous allons maintenant appliquer cette méthode à ton propre site. Dans les modules précédents,
      tu as commencé à construire une stratégie de contenu et à identifier tes pages importantes.
      Nous allons examiner si certains sites proposent déjà des liens vers tes ressources.
      L'objectif n'est pas encore de rechercher de nouvelles opportunités ou d'envoyer des demandes
      de partenariat, mais de découvrir les informations disponibles et d'apprendre à reconnaître
      les backlinks qui possèdent une justification claire.
    </p>
    <p><strong>Durée estimée : 10 à 15 minutes.</strong></p>
    <h3>Étape 1 — Ouvre le rapport sur les liens</h3>
    <p>
      Commence par ouvrir Google Search Console et sélectionner la propriété correspondant à ton
      site. Accède ensuite au rapport « Liens ». Dans la section consacrée aux liens externes,
      examine les principaux sites d'origine et les pages de destination présentées. Essaie de
      comprendre quelles ressources de ton site reçoivent déjà des références. Si le rapport ne
      présente aucune information, ne considère pas cela comme un échec : note simplement que tu ne
      disposes pas encore de backlinks identifiables dans les données affichées.
    </p>
    <h3>Étape 2 — Examine un ou deux liens existants</h3>
    <p>
      Si des liens sont disponibles, sélectionne un ou deux domaines qui semblent intéressants.
      Essaie de retrouver les pages sur lesquelles les liens apparaissent, puis observe leur sujet,
      le contexte de la mention et la destination du lien. Le lecteur possède-t-il une raison claire
      de consulter ta page ? Le lien correspond-il à une ressource réellement utile ? Vérifie
      également que la page de destination fonctionne correctement. Tu n'as pas besoin de calculer
      un score ou d'installer un outil SEO supplémentaire pour réaliser cette première analyse.
    </p>
    <h3>Étape 3 — Identifie les contenus qui pourraient être cités</h3>
    <p>
      Reprends maintenant les pages importantes de ton site et demande-toi lesquelles pourraient
      présenter un intérêt pour une publication extérieure. Il peut s'agir d'un guide pédagogique,
      d'une réalisation, d'une étude de cas ou d'une ressource qui apporte une réponse précise à une
      question fréquente. L'objectif n'est pas de supposer que chaque contenu recevra naturellement
      des liens, mais d'identifier une page qui pourrait être utile à quelqu'un souhaitant
      approfondir un sujet ou présenter ton activité. Si aucun contenu ne semble encore correspondre
      à ce besoin, tu peux noter qu'il serait intéressant d'améliorer une ressource existante avant
      de chercher à la faire connaître.
    </p>
    <h3>Étape 4 — Conserve ton point de départ</h3>
    <p>
      Pour terminer, note les observations réalisées. Tu peux conserver les principaux domaines
      identifiés, les pages de ton site qui reçoivent des liens et les références dont le contexte
      te semble pertinent. Si tu ne possèdes pas encore de backlinks, conserve simplement cette
      situation comme point de départ. Choisis également une page qui pourrait mériter d'être
      davantage connue. Tu pourras utiliser ces informations dans la prochaine leçon pour rechercher
      des opportunités de mentions et de liens adaptées à ton activité.
    </p>
    <p>
      <strong>Ton résultat attendu :</strong> avoir consulté ton profil de backlinks dans Google
      Search Console, examiné jusqu'à deux références lorsqu'elles existent et identifié une
      ressource de ton site qui pourrait présenter un intérêt pour d'autres publications.
    </p>
    <p>
      Tu n'as pas besoin d'obtenir un nouveau backlink pour valider cet exercice. Ces observations
      alimenteront l'action « Identifier mes premières opportunités de backlinks » dans « Mon plan
      d'action », que tu pourras finaliser à la fin du module 7.
    </p>
    <h2>Ce qu'il faut retenir</h2>
    <p>
      Un backlink correspond à un lien présent sur un autre site et qui dirige vers une page de ton
      propre site. Ces liens peuvent permettre aux internautes de découvrir tes contenus, contribuer
      à la notoriété de ton activité et faire partie des signaux utilisés par les moteurs de
      recherche pour comprendre les relations entre les pages. Google utilise notamment des systèmes
      d'analyse des liens, parmi lesquels PageRank, mais les backlinks ne représentent qu'une partie
      des nombreux éléments intervenant dans le référencement naturel.
    </p>
    <p>
      Nous avons également découvert la notion d'autorité, qui permet de réfléchir à la
      reconnaissance et à la crédibilité d'un site dans son environnement. Il faut cependant
      distinguer ce concept des scores proposés par les outils SEO. Le Domain Rating, le Domain
      Authority et le Trust Flow sont des métriques privées. Elles peuvent aider à examiner un
      profil de liens, mais ne constituent pas des notes attribuées par Google. Il n'existe donc pas
      de seuil de DR, de DA ou de TF garantissant qu'un site pourra se positionner.
    </p>
    <p>
      Nous avons aussi appris à distinguer le nombre de backlinks du nombre de domaines référents et
      à comprendre pourquoi les outils peuvent présenter des chiffres différents. Enfin, nous avons
      découvert plusieurs éléments utiles pour examiner un lien : sa pertinence, son contexte
      éditorial, la qualité de la ressource d'origine, sa destination et son texte d'ancrage. Les
      attributs <code>nofollow</code>, <code>sponsored</code> et <code>ugc</code> permettent
      également de fournir des informations sur la nature de certains liens, sans permettre à eux
      seuls de calculer leur effet sur le référencement.
    </p>
    <p>
      <strong
        >L'objectif d'une bonne stratégie de netlinking ne consiste pas à accumuler le plus grand
        nombre de liens. Il consiste à développer des références pertinentes, justifiées et utiles
        pour les personnes qui découvrent ton activité.</strong
      >
    </p>
    <p>
      Tu comprends désormais pourquoi les backlinks peuvent contribuer au référencement et comment
      commencer à examiner ceux qui pointent vers ton site.
    </p>
