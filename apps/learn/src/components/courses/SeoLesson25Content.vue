      site.
    </p>
    <p>
      Lorsqu'un assistant propose une URL cliquable, l'utilisateur peut consulter la ressource
      correspondante.
    </p>
    <p>Mais la présence d'un lien ne signifie pas qu'il a été utilisé.</p>
    <p>
      Il faut donc distinguer un lien affiché dans une réponse d'une visite réellement enregistrée
      par ton site.
    </p>
