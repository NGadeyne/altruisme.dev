    <p>Ces outils peuvent être intéressants lorsque tu souhaites industrialiser ton suivi.</p>
    <p>Mais il faut comprendre ce qu'ils mesurent réellement.</p>
    <p>
      Un outil peut effectuer une série de requêtes à partir de formulations prédéfinies, puis
      analyser les réponses obtenues.
    </p>
    <p>
      Un autre peut utiliser des modèles, des modes de recherche, des localisations ou des
      protocoles différents.
    </p>
    <p>Les résultats ne sont donc pas nécessairement comparables.</p>
    <p>
      Imaginons qu'une plateforme indique que notre photographe possède un score de visibilité de 42
      sur 100.
    </p>
    <p>Ce score dépend de sa méthode de calcul.</p>
    <p>Il ne correspond pas à une note officielle publiée par ChatGPT ou Gemini.</p>
    <p>Il ne garantit pas non plus que 42 % des utilisateurs découvrent réellement l'entreprise.</p>
    <p>
      Ces outils peuvent faciliter le suivi, mais leurs indicateurs doivent être compris avant
      d'être utilisés pour prendre des décisions.
    </p>
