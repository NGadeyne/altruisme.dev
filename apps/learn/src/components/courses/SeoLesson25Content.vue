    <p>Elle cherche simplement à influencer artificiellement le comportement d'un système.</p>
    <p>
      Les assistants modernes peuvent utiliser des protections contre ces instructions, et rien ne
      garantit que cette démarche produise l'effet attendu.
    </p>
    <p>Elle ne constitue donc pas une stratégie GEO fiable.</p>
