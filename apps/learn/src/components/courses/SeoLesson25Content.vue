      performances dans l'IA générative.
    </p>
    <p>
      Ces rapports concernent notamment les Aperçus IA et le Mode IA, avec une vue distincte pour
      certaines fonctionnalités de Google Discover.
    </p>
    <p>
      Il devient donc possible d'examiner des impressions associées aux fonctionnalités IA de
      Google, sans se limiter à des recherches manuelles.
    </p>
    <h3>Comprendre les impressions dans les fonctionnalités IA</h3>
    <p>
      Dans le rapport dédié à l'IA générative dans la Recherche, une impression correspond à
      l'apparition d'un lien vers ton site dans une fonctionnalité IA prise en charge, selon les
      règles de comptabilisation de Google.
    </p>
    <p>Cela ne signifie pas nécessairement que l'utilisateur a cliqué sur ce lien.</p>
    <p>
      Cela ne signifie pas non plus que ton entreprise a été mentionnée textuellement dans la
      réponse.
    </p>
    <p>Le rapport mesure une forme de visibilité liée aux URL présentées.</p>
    <p>Imaginons que notre photographe possède un guide consacré au choix d'un professionnel.</p>
    <p>
      Si Google présente ce guide comme lien dans un Aperçu IA et que cette apparition répond aux
      conditions de comptabilisation, elle peut contribuer aux impressions du rapport.
    </p>
    <p>
      Cette donnée est plus directement observable qu'une simple estimation fondée sur quelques
      recherches manuelles.
    </p>
    <p>Mais elle reste limitée aux fonctionnalités de Google couvertes par le rapport.</p>
    <p>Elle ne mesure pas la visibilité dans ChatGPT ou Gemini.</p>
    <h3>Les informations disponibles dans le rapport</h3>
    <p>
      Le rapport permet notamment d'examiner les impressions au fil du temps et les pages de ton
      site qui apparaissent dans ces fonctionnalités.
    </p>
    <p>Il propose également des dimensions comme le pays, le type d'appareil et la date.</p>
    <p>
      Tu peux donc identifier les URL qui bénéficient déjà d'une visibilité dans les fonctionnalités
      IA de Google.
    </p>
    <p>
      Imaginons que notre photographe découvre que son guide sur le choix d'un professionnel reçoit
      des impressions, tandis que son guide sur les photographies de groupe n'en présente aucune.
    </p>
    <p>
      Cette observation peut l'aider à comprendre quelles ressources sont actuellement affichées
      dans les expériences concernées.
    </p>
    <p>Mais elle ne prouve pas que le deuxième guide est inutile ou inaccessible.</p>
    <p>
      Les recherches effectuées par les internautes, leur fréquence et les choix des systèmes de
      Google peuvent expliquer des différences importantes entre les pages.
    </p>
    <p>
      Il faut également noter que le rapport dédié présente principalement des données
      d'impressions, et non une liste exhaustive de toutes les questions ayant généré les réponses
      IA.
    </p>
    <p>
      Les impressions associées aux fonctionnalités IA restent incluses dans les données globales de
      performance de la recherche Web, selon les règles de Google.
    </p>
    <h3>Et si le rapport ne s'affiche pas ?</h3>
    <p>
