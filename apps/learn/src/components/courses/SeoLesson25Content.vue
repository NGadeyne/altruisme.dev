      Imaginons que notre photographe soit cité dix fois dans différents résultats, mais qu'aucun
      visiteur ne clique sur ses liens.
    </p>
    <p>
      Cette situation représente une visibilité documentaire observée, mais pas nécessairement une
      acquisition de trafic.
    </p>
    <p>
      À l'inverse, une seule référence particulièrement pertinente peut éventuellement conduire une
      personne vers son formulaire de contact.
    </p>
    <p>
      Il est donc utile d'examiner plusieurs dimensions plutôt que de se concentrer sur un chiffre
      unique.
    </p>
    <p>
      <strong
        >Une mention, une citation et une visite correspondent à trois résultats différents. Ils
        peuvent être liés, mais ne doivent pas être confondus.</strong
      >
