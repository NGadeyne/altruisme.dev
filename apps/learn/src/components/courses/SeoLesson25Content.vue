    <p>Il peut simplement ne pas disposer des données nécessaires à l'affichage du rapport.</p>
    <p>
      Si tu souhaites vérifier ton paramétrage, Google Search Console propose également une section
      consacrée au contrôle de l'IA générative dans la Recherche.
    </p>
    <p>
      Ce réglage permet notamment de choisir l'inclusion ou l'exclusion de son contenu dans les
      fonctionnalités IA concernées de Google.
    </p>
    <p>Il est distinct de la gestion de l'entraînement des modèles.</p>
    <p>
      Pour ton diagnostic, contente-toi de vérifier le paramètre appliqué à ta propriété, sans le
      modifier à l'aveugle.
    </p>
    <p>
      <strong
        >Search Console permet d'observer une partie de ta visibilité IA dans Google, mais ne
        constitue pas un tableau de bord universel couvrant tous les assistants et moteurs
        génératifs.</strong
      >
    </p>
    <h2>Mesurer les visites provenant de ChatGPT et des autres assistants</h2>
    <p>Une autre source d'information importante concerne les statistiques de ton site.</p>
    <p>
      Lorsqu'un utilisateur clique sur un lien proposé par un assistant, il peut arriver sur l'une
      de tes pages.
    </p>
    <p>
      Selon les informations transmises et la configuration de ton outil d'analyse, cette visite
      peut être attribuée à une source identifiable.
    </p>
    <p>
      OpenAI indique notamment que les liens provenant des résultats de recherche ChatGPT incluent
      le paramètre <code>utm_source=chatgpt.com</code>, permettant aux éditeurs de reconnaître une
      partie de ce trafic dans leurs outils d'analyse.
    </p>
    <p>
      Si tu utilises Google Analytics ou un outil équivalent, tu peux donc rechercher les visites
      associées à cette source.
    </p>
    <p>Mais attention à ne pas confondre cette mesure avec le nombre de citations.</p>
    <p>Un assistant peut citer ton site sans que personne ne clique.</p>
    <p>
      À l'inverse, une personne peut découvrir ton entreprise dans une réponse, puis effectuer une
      recherche classique sur Google pour retrouver ton site.
    </p>
    <p>
      Dans ce deuxième cas, la visite pourrait être attribuée à Google plutôt qu'à l'assistant qui a
      contribué à la découverte.
    </p>
    <p>
      Les outils d'analyse ne reconstituent donc pas toujours l'ensemble du parcours du visiteur.
    </p>
    <h3>Observer les pages qui reçoivent des visites</h3>
    <p>Imaginons que notre photographe utilise un outil de mesure d'audience.</p>
