    <h2>Comprendre les trois critères du classement local</h2>
    <p>
      Nous arrivons maintenant à l'un des points essentiels de cette leçon. Google explique que ses
      résultats locaux reposent principalement sur trois dimensions :
      <strong>la pertinence, la distance et la notoriété</strong>, également appelée proéminence.
      Ces critères permettent de comprendre pourquoi certains établissements apparaissent dans
      Google Maps ou dans les résultats locaux de Google Search. Ils ne correspondent toutefois pas
      à trois scores publics que tu pourrais consulter dans un tableau de bord, et Google ne publie
      pas la pondération exacte de tous les éléments utilisés.
    </p>
    <p>
      La première dimension est la <strong>pertinence</strong>. Elle correspond à la relation entre
      la recherche effectuée par l'utilisateur et les informations disponibles sur l'établissement.
      Imaginons qu'une personne recherche un photographe de mariage à Bordeaux. Google doit
      identifier des professionnels dont l'activité correspond à cette demande. Une entreprise
      spécialisée dans la photographie immobilière ne répond pas nécessairement à la même intention
      qu'un professionnel proposant des reportages de mariage. Les informations renseignées dans la
      fiche, notamment la catégorie principale et les prestations proposées, peuvent contribuer à
      cette compréhension. Mais il ne faut pas confondre pertinence et accumulation de mots-clés.
      Inscrire « meilleur photographe mariage Bordeaux pas cher » dans le nom d'une entreprise ne
      constitue pas une bonne optimisation lorsque ce texte ne correspond pas à son nom réel. Le
      choix des catégories et la description des services doivent refléter fidèlement l'activité
      exercée.
    </p>
    <p>
      La deuxième dimension est la <strong>distance</strong>. Google peut tenir compte de
      l'éloignement entre l'établissement et la localisation associée à la recherche. Imaginons
      qu'une personne cherche un coiffeur depuis le centre de Bordeaux. Les établissements proposés
      peuvent être différents de ceux affichés pour la même recherche effectuée depuis Mérignac. Le
      contexte géographique a changé, et il peut influencer les résultats. Mais cela ne signifie pas
      que l'établissement le plus proche apparaît systématiquement en premier. Google combine la
      distance avec les autres dimensions de son classement. Un professionnel un peu plus éloigné
      peut donc apparaître lorsqu'il correspond particulièrement bien à la recherche ou possède une
      notoriété importante.
    </p>
    <p>
      La troisième dimension est la <strong>notoriété</strong>. Elle correspond à la manière dont
      une entreprise est connue et reconnue. Google peut notamment tenir compte d'informations
      disponibles sur le Web, de liens provenant d'autres sites et des avis associés à
      l'établissement. Imaginons que notre photographe travaille régulièrement avec des lieux de
      réception, participe à des événements locaux et reçoive des avis authentiques de ses clients.
      Ces références peuvent contribuer à sa présence professionnelle et à sa reconnaissance. Nous
      retrouvons ici plusieurs notions étudiées dans le module consacré aux backlinks : une
      entreprise ne développe pas sa notoriété uniquement à travers ce qu'elle publie sur son propre
      site. Ses relations et ses références externes peuvent également compter.
