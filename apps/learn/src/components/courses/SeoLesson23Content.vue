      pour sélectionner les établissements proposés.
    </p>
    <p>
      <strong
        >La visibilité locale résulte principalement de la combinaison entre la pertinence de
        l'entreprise, sa distance par rapport à la recherche et sa notoriété. Aucun de ces critères
        ne garantit à lui seul une position.</strong
      >
