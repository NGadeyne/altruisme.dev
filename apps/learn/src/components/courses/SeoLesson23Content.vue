      plusieurs recherches géographiques, mais elle ne garantit pas une meilleure visibilité et peut
      produire des contenus de faible valeur.
    </p>
    <p>
      Dans les modules précédents, nous avons appris qu'une page doit répondre à une intention
      réelle et proposer des informations utiles. Cette règle reste valable pour le référencement
      local. Si plusieurs pages répètent exactement les mêmes prestations, les mêmes exemples et les
      mêmes explications, elles n'apportent pas nécessairement de valeur supplémentaire. Google
      considère notamment certaines pages créées principalement pour capter des recherches
      similaires et diriger les utilisateurs vers une même destination comme des pages satellites,
