    <h2>Préparer un contenu original à l'heure de l'intelligence artificielle</h2>
    <p>
      Il est aujourd'hui possible d'utiliser des outils d'intelligence artificielle pour rechercher
      des idées, organiser des notes, proposer des plans ou préparer certaines formulations.
    </p>
    <p>
      Ces fonctionnalités peuvent être utiles pour gagner du temps pendant la préparation
      éditoriale.
    </p>
    <p>
      Mais elles ne remplacent pas la compréhension du besoin, la vérification des informations et
      la responsabilité de la personne qui publie le contenu.
    </p>
    <p>
      Imaginons que notre photographe demande à un outil d'IA de rédiger un article complet sur les
      délais de réservation.
    </p>
    <p>L'outil pourrait produire rapidement plusieurs paragraphes bien structurés.</p>
    <p>
      Mais ces paragraphes pourraient contenir des recommandations générales, des affirmations non
      vérifiées ou des délais présentés comme universels alors qu'ils varient selon les situations.
    </p>
    <p>
      Le contenu pourrait également ne rien apporter de particulier par rapport aux nombreuses
      ressources déjà disponibles.
    </p>
    <p>
      C'est pourquoi il est important de distinguer l'aide à la préparation de la production
      automatique d'informations réellement utiles.
    </p>
    <p>
      Google ne considère pas qu'un contenu est de mauvaise qualité simplement parce qu'une IA a
      participé à sa création. En revanche, produire de nombreuses pages principalement pour
      manipuler les classements, sans apporter de valeur aux internautes, peut relever de ses règles
      concernant le spam.
    </p>
    <p>
      Pour cette formation, retiens surtout un principe :
      <strong
        >l'outil utilisé pour produire un contenu ne détermine pas à lui seul sa qualité. Ce qui
        compte, c'est l'exactitude, l'originalité, l'utilité et la pertinence de la réponse
        proposée.</strong
      >
    </p>
    <p>
      Tu peux donc utiliser une IA pour organiser tes idées ou identifier des questions à
      approfondir, mais les informations doivent être vérifiées.
    </p>
    <p>
      Les exemples présentés doivent correspondre à des situations réelles ou être clairement
      identifiés comme fictifs.
    </p>
    <p>
      Les affirmations importantes doivent pouvoir être justifiées, et la version publiée doit être
      relue avec attention.
    </p>
    <p>Le lecteur doit pouvoir comprendre pourquoi il peut accorder sa confiance au contenu.</p>
