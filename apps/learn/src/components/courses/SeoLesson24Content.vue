      représentent plus correctement l'établissement ou les prestations. Il ne s'agit pas
      d'interdire le travail artistique normal d'un photographe, mais de préserver la sincérité des
      informations présentées.
    </p>
    <h3>Privilégier la qualité et l'utilité des images</h3>
    <p>
      Une fiche contenant quelques photographies pertinentes peut être plus utile qu'une galerie
      remplie de contenus répétitifs. Notre photographe n'a pas besoin d'importer des centaines
      d'images pour montrer qu'il exerce son activité. Il peut commencer par une sélection variée :
      quelques reportages, des exemples de portraits et éventuellement des images permettant de
      mieux comprendre son approche.
    </p>
    <p>
      Les photographies doivent également respecter les exigences techniques de Google. Pour les
      images, Google recommande notamment des formats JPG ou PNG, une taille de fichier adaptée et
      une résolution suffisante. La plateforme peut vérifier les contenus avant leur publication et
      certaines images peuvent être refusées lorsqu'elles ne respectent pas ses règles.
    </p>
    <p>
