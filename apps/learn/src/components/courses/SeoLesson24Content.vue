    <h3>Présenter les services sans multiplier les mots-clés</h3>
    <p>
      Selon la catégorie d'activité, Google permet également de renseigner des services et parfois
      leurs descriptions ou leurs prix. Ces fonctionnalités peuvent varier selon le secteur et les
      options disponibles.
    </p>
    <p>
      Notre photographe pourrait par exemple présenter les reportages de mariage, les séances de
      couple ou d'autres prestations qu'il réalise réellement. Chaque service doit correspondre à
      une offre existante. Il ne faut pas inventer des activités simplement parce qu'elles semblent
      recherchées dans Google.
    </p>
    <p>
      Les intitulés doivent rester compréhensibles pour les clients. Une prestation appelée «
      Reportage photo de mariage » est généralement plus claire qu'une longue expression constituée
      de mots-clés géographiques répétés.
    </p>
    <p>
      Si un service nécessite une explication particulière, la description peut préciser ce qu'il
      comprend et les conditions importantes. Mais la fiche n'a pas besoin de reproduire
      l'intégralité des pages commerciales du site. Elle doit permettre de découvrir l'offre, puis
      de consulter les informations détaillées lorsque cela est nécessaire.
    </p>
    <p>
      <strong
        >La bonne description est celle qui aide un futur client à comprendre ton entreprise. Elle
        n'a pas besoin d'être écrite comme une succession de requêtes Google.</strong
