      Un artisan peut montrer des réalisations. Un commerce peut aider les visiteurs à reconnaître
      sa devanture. Pour notre photographe, les images jouent évidemment un rôle central
      puisqu'elles permettent de découvrir directement son travail.
    </p>
    <p>
      Google permet notamment d'ajouter un logo, une photographie de couverture et d'autres images
      présentant l'entreprise, ses services ou ses réalisations. Mais ces différents éléments ne
      sont pas nécessairement affichés exactement dans l'ordre souhaité. Google peut sélectionner
      les visuels qu'il considère comme les plus appropriés, et les utilisateurs peuvent également
      contribuer à certaines photographies visibles sur une fiche.
    </p>
    <p>
      Il faut donc éviter de considérer qu'ajouter une couverture garantit qu'elle apparaîtra
      systématiquement en première position. L'objectif est plutôt de fournir des images de qualité,
      suffisamment représentatives pour aider les visiteurs à comprendre l'entreprise.
    </p>
    <p>
