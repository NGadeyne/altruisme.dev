      <code>rel="nofollow"</code>.
    </p>
    <p>Le problème n'est donc pas l'existence d'une relation commerciale en elle-même.</p>
    <p>
      Il apparaît lorsqu'un lien rémunéré cherche à transmettre artificiellement des signaux de
      classement sans être correctement qualifié.
    </p>
