      désaveu de liens.
    </p>
    <p>
      Elle permet de transmettre à Google un fichier contenant des URL ou des domaines dont tu
      souhaites qu'il ignore les liens pour l'évaluation de ton site.
    </p>
    <p>
      Sur le papier, cet outil pourrait sembler idéal pour supprimer les backlinks de mauvaise
      qualité.
    </p>
    <p>Mais son utilisation demande beaucoup de prudence.</p>
    <p>
      Google explique que, dans la plupart des situations, ses systèmes sont capables d'évaluer les
      liens sans intervention supplémentaire.
    </p>
    <p>L'outil de désaveu n'est donc pas utile à la majorité des propriétaires de sites.</p>
    <h3>Dans quels cas peut-il être nécessaire ?</h3>
    <p>
      Google recommande d'envisager le désaveu principalement lorsqu'un nombre considérable de liens
      artificiels, de mauvaise qualité ou associés à du spam pointe vers un site et que ces liens
      ont provoqué, ou sont susceptibles de provoquer, une action manuelle.
    </p>
    <p>
      Imaginons qu'une entreprise ait volontairement acheté des milliers de backlinks dans le cadre
      d'une stratégie de manipulation des classements.
    </p>
    <p>
      Elle décide ensuite de mettre fin à cette pratique et de rétablir une situation conforme aux
      règles de Google.
    </p>
    <p>Dans ce contexte, une analyse approfondie des liens concernés peut être nécessaire.</p>
    <p>
      Google recommande notamment de chercher d'abord à faire supprimer ou qualifier correctement
      les liens artificiels lorsqu'il est possible de contacter les propriétaires des sites
      concernés.
    </p>
    <p>
      Le désaveu peut ensuite intervenir pour les références problématiques qui n'ont pas pu être
      retirées.
    </p>
    <p>Mais cette démarche ne correspond pas à une opération de maintenance ordinaire.</p>
    <h3>Pourquoi ne faut-il pas désavouer tous les liens suspects ?</h3>
    <p>
      Imaginons que notre photographe découvre cinq backlinks provenant de domaines affichant des
      scores faibles.
    </p>
    <p>Il pourrait être tenté d'ajouter immédiatement ces domaines à son fichier de désaveu.</p>
    <p>
      Mais certains de ces liens peuvent être légitimes. D'autres peuvent être simplement ignorés
      par les systèmes de Google.
    </p>
    <p>
      En les désavouant sans analyse, il pourrait demander à Google de ne pas tenir compte de
      références qui ne posaient aucun problème.
    </p>
    <p>
      L'outil peut donc entraîner des conséquences indésirables lorsqu'il est utilisé à l'aveugle.
    </p>
    <p>
      Il ne faut pas non plus désavouer automatiquement tous les liens provenant d'un pays étranger,
      tous les liens <code>nofollow</code> ou tous les domaines signalés par un logiciel.
    </p>
    <p>
      <strong
        >Pour un débutant, la bonne démarche consiste généralement à comprendre les backlinks et à
        éviter les pratiques artificielles, pas à utiliser systématiquement l'outil de
        désaveu.</strong
      >
    </p>
    <p>
      Si ton site fait réellement l'objet d'une action manuelle pour liens artificiels, ou si tu
      découvres une campagne importante de liens manipulateurs associée à ton activité, il peut être
      préférable de demander un diagnostic à un professionnel expérimenté avant d'intervenir.
    </p>
    <h2>Que faire lorsqu'un backlink disparaît ou pointe vers une ancienne page ?</h2>
    <p>Les problèmes rencontrés dans un profil de liens ne concernent pas uniquement le spam.</p>
    <p>
      Certains backlinks peuvent devenir inutilisables lorsque des pages changent d'adresse ou
      disparaissent.
    </p>
    <p>Reprenons notre photographe.</p>
    <p>
      Un organisateur de mariage a publié un lien vers son ancien portfolio, accessible à l'adresse
      <code>/portfolio-mariages</code>.
    </p>
    <p>
      Mais notre photographe a récemment réorganisé son site et déplacé ses réalisations vers
      <code>/realisations/mariages</code>.
    </p>
    <p>L'ancienne URL renvoie désormais une erreur 404.</p>
    <p>Dans cette situation, le problème ne vient pas de la qualité du backlink.</p>
    <p>Il vient du fait que la ressource attendue n'est plus accessible à son ancienne adresse.</p>
    <p>
      Si la nouvelle page correspond réellement à l'ancien contenu, une redirection permanente
      appropriée peut permettre de rétablir le parcours.
    </p>
    <p>
      Il peut également être utile de contacter le partenaire pour lui proposer de mettre à jour son
      lien directement.
    </p>
    <p>Nous retrouvons ici les principes étudiés dans la leçon 14.</p>
    <p>
      À l'inverse, si la page a été supprimée volontairement et qu'aucun contenu équivalent
      n'existe, il n'est pas nécessaire de rediriger artificiellement l'ancienne URL vers une page
      sans rapport.
    </p>
    <p>Une réponse 404 ou 410 peut être parfaitement normale.</p>
    <h3>Faut-il récupérer tous les backlinks perdus ?</h3>
    <p>Pas nécessairement.</p>
    <p>
      Un lien peut disparaître parce qu'un site a supprimé un article, réorganisé ses contenus ou
      cessé son activité.
    </p>
    <p>Cela fait partie de l'évolution normale du Web.</p>
    <p>
      Il peut être intéressant de vérifier une référence importante, notamment lorsqu'elle provient
      d'un partenaire ou d'une publication apportant des visiteurs.
    </p>
    <p>
      Mais chercher à récupérer systématiquement chaque lien disparu peut représenter beaucoup de
      travail pour un bénéfice limité.
    </p>
    <p>
      Comme pour les autres dimensions du SEO, il faut prioriser les situations réellement
      importantes.
    </p>
