      observer les variations de certaines recherches au fil des saisons.
    </p>
    <p>
      Google Trends permet également de comparer plusieurs termes et de consulter des recherches
      associées, lorsque les données sont suffisantes.
    </p>
    <h3>Attention : Google Trends ne donne pas un volume de recherche exact</h3>
    <p>C'est probablement la notion la plus importante à retenir concernant cet outil.</p>
    <p>
      Google Trends ne présente pas directement le nombre exact de recherches mensuelles pour une
      expression.
    </p>
    <p>
      Il utilise des données normalisées, généralement représentées sur une échelle allant de 0 à
      100.
    </p>
    <p>
      Un indice de 100 correspond à un niveau de popularité relative maximal dans le périmètre
      étudié, et non à 100 recherches.
    </p>
    <p>De même, un indice de 50 ne signifie pas qu'une expression a été recherchée 50 fois.</p>
    <p>
      Les résultats dépendent notamment de la période, de la zone géographique et des termes
      comparés.
    </p>
    <p>Il est donc essentiel de ne pas interpréter ces chiffres comme des volumes absolus.</p>
    <p>
      Il faut également savoir que les recherches très spécifiques peuvent ne pas disposer de
      suffisamment de données pour produire une courbe exploitable.
    </p>
    <p>
      Si tu explores une expression très précise liée à une petite zone géographique, Google Trends
      peut afficher peu d'informations ou des résultats difficiles à interpréter.
    </p>
    <p>Cela ne signifie pas nécessairement que personne ne recherche cette expression.</p>
    <p>
      Pour commencer, utilise donc Google Trends comme un outil complémentaire permettant d'observer
      des tendances, et non comme une méthode destinée à attribuer un volume exact à chaque mot-clé.
    </p>
    <h2>Faut-il absolument connaître le volume de recherche ?</h2>
