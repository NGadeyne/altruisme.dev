    <h2>Qu'est-ce qu'une recherche de mots-clés ?</h2>
    <p>
      La recherche de mots-clés, également appelée <em>keyword research</em>, consiste à identifier
      les mots et les expressions que les internautes utilisent lorsqu'ils recherchent des
      informations, des produits ou des services liés à une activité.
    </p>
    <p>
      L'objectif n'est pas simplement de trouver des expressions populaires. Il s'agit de comprendre
