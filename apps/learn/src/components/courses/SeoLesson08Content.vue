    <h3>Les limites de Search Console</h3>
    <p>
      Il faut toutefois comprendre que Google Search Console ne remplace pas une recherche complète
      de mots-clés.
    </p>
    <p>
      D'abord, l'outil présente des informations sur les recherches pour lesquelles ton site possède
