      classement direct que l'on pourrait optimiser simplement en ajoutant quelques éléments à une
      page.
    </p>
    <p>
      Il s'agit plutôt d'un cadre utile pour réfléchir à la qualité et à la confiance que peut
      inspirer un contenu.
    </p>
