    <p>
      La page doit donc présenter suffisamment clairement ta prestation pour lui permettre d'évaluer
      son intérêt.
    </p>
    <p>
      Un guide pédagogique, à l'inverse, doit principalement répondre à une question ou permettre de
      comprendre un sujet.
    </p>
    <p>
      Si une personne recherche « pourquoi mon site n'apparaît pas sur Google », elle attend
      probablement des explications sur les causes possibles et les premières vérifications à
      effectuer.
    </p>
    <p>Elle n'a pas nécessairement envie de lire immédiatement une présentation commerciale.</p>
    <p>
      Enfin, une fiche produit doit généralement aider le visiteur à comprendre les caractéristiques
      du produit, sa disponibilité, son prix et les conditions d'achat.
    </p>
    <p>Les informations attendues dépendent donc de l'intention.</p>
