      comprendre sur quoi reposent tes explications.
    </p>
    <p>
      <strong
        >La confiance ne se construit pas uniquement en affirmant que tu es expert. Elle se
        construit en montrant ce que tu sais, ce que tu fais et pourquoi tes informations sont
        fiables.</strong
      >
    </p>
    <h2>Adapter son contenu au type de page</h2>
    <p>Toutes les pages d'un site n'ont pas la même fonction.</p>
    <p>
