    <p>
      Le rôle d'un moteur de recherche comme Google est de proposer aux internautes des résultats
      qu'il estime pertinents et utiles. Pour cela, il utilise différents systèmes capables
      notamment d'analyser les contenus, les liens et de nombreux autres signaux.
    </p>
    <p>
      Ton objectif n'est donc pas de trouver une astuce qui permettrait de tromper son
      fonctionnement. Il est plutôt de
      <strong
        >construire un site compréhensible, accessible et réellement utile aux personnes auxquelles
        tu t'adresses</strong
      >.
    </p>
